_WORKER_BAM = None
_WORKER_PI_TRANS = None
_WORKER_A0 = None
_WORKER_ARGS = None


def init_candidate_worker(bam_path: str, pi_trans: np.ndarray, A0: float, args: argparse.Namespace) -> None:
    require_worker_dependencies()
    global _WORKER_BAM, _WORKER_PI_TRANS, _WORKER_A0, _WORKER_ARGS
    _WORKER_BAM = None if _ACTIVE_PSITE_INDEX is not None else pysam.AlignmentFile(bam_path, "rb")
    _WORKER_PI_TRANS = np.asarray(pi_trans, dtype=float)
    _WORKER_A0 = float(A0)
    _WORKER_ARGS = args


def candidate_worker(payload: Tuple[ORFRow, np.random.SeedSequence]) -> Dict[str, object]:
    require_worker_dependencies()
    row, seed = payload
    has_prepared = row.prepared_mat_core is not None and row.prepared_core_indices is not None
    if ((_WORKER_BAM is None and _ACTIVE_PSITE_INDEX is None and not has_prepared)
            or _WORKER_PI_TRANS is None or _WORKER_A0 is None or _WORKER_ARGS is None):
        raise RuntimeError("Candidate worker was not initialized")
    rng = np.random.default_rng(seed)
    return analyze_candidate(_WORKER_BAM, row, _WORKER_PI_TRANS, _WORKER_A0, _WORKER_ARGS, rng)


def stable_candidate_seed(row: ORFRow, args: argparse.Namespace) -> np.random.SeedSequence:
    """Derive an order-independent RNG seed from the analyzed candidate identity."""
    overlap_type = candidate_overlap_type(row) or "invalid"
    identity = repr(_candidate_group_key(row, overlap_type, args.candidate_dedup)).encode("utf-8")
    digest = hashlib.blake2b(
        identity,
        digest_size=16,
        person=b"intorf-dm-rng",
    ).digest()
    digest_words = [int.from_bytes(digest[i:i + 4], "little") for i in range(0, len(digest), 4)]
    return np.random.SeedSequence([int(args.seed), *digest_words])


