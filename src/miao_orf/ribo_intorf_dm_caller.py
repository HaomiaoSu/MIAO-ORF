def analyze_candidate(
    bam: pysam.AlignmentFile,
    row: ORFRow,
    pi_trans: np.ndarray,
    A0: float,
    args: argparse.Namespace,
    rng: np.random.Generator,
) -> Dict[str, object]:
    out = base_result(row)
    out["importance_compute_mode"] = args.importance_mode_used
    overlap_type = candidate_overlap_type(row)
    out["overlap_type"] = overlap_type or ""

    if overlap_type is None:
        out["classification_pre_fdr"] = "invalid_overlap_type"
        out["p_final"] = 1.0
        return out

    pi_host = pi_host_for_type(pi_trans, overlap_type)
    out.update({
        "pi_trans_0": float(pi_trans[0]), "pi_trans_1": float(pi_trans[1]), "pi_trans_2": float(pi_trans[2]),
        "pi_host_0": float(pi_host[0]), "pi_host_1": float(pi_host[1]), "pi_host_2": float(pi_host[2]),
        "A0": float(A0),
    })

    dom = 2 if overlap_type == "F1" else 1
    gain_denom = float(pi_trans[0] - pi_host[0])
    drop_denom = float(pi_host[dom] - pi_trans[dom])
    template_separation_ok = int(
        abs(gain_denom) >= args.template_separation_min
        and abs(drop_denom) >= args.template_separation_min
    )
    out.update({
        "host_dominant_index": dom,
        "template_separation_ok": template_separation_ok,
    })
    if template_separation_ok != 1:
        out["classification_pre_fdr"] = "template_separation_too_small"
        out["p_final"] = 1.0
        return out

    if row.peptide_len < args.min_intorf_aa:
        out["classification_pre_fdr"] = "too_short"
        out["p_final"] = 1.0
        return out

    if row.prepared_mat_core is not None and row.prepared_core_indices is not None:
        counts = np.asarray(row.prepared_mat_core, dtype=int)
        active_indices = np.asarray(row.prepared_core_indices, dtype=int)
        read_metrics = dict(row.prepared_read_metrics or {})
        n_total_codons = safe_int(
            read_metrics.get("n_total_orf_codons_including_stop"),
            max(0, row.orf_len_nt // 3),
        )
        n_core_codons = safe_int(
            read_metrics.get("n_core_codons"),
            max(
                0,
                n_total_codons
                - max(0, int(args.exclude_start_codons))
                - max(0, int(args.exclude_stop_codons)),
            ),
        )
        n_active = safe_int(read_metrics.get("n_active_core_codons"), len(counts))
        core_reads = safe_int(read_metrics.get("core_reads"), counts.sum())
    else:
        tcounts = count_psites_by_tindex(bam, row, args.rl, args.rl_source)
        mat_all = codon_count_matrix(tcounts, row.orf_len_nt)
        n_total_codons = len(mat_all)
        core_start = max(0, int(args.exclude_start_codons))
        core_end = max(core_start, n_total_codons - max(0, int(args.exclude_stop_codons)))
        mat_core = mat_all[core_start:core_end]
        core_indices = np.arange(core_start, core_end, dtype=int)
        n_core_codons = len(mat_core)
        ns_core = mat_core.sum(axis=1) if n_core_codons else np.array([], dtype=int)
        active_mask = ns_core > 0
        counts = mat_core[active_mask]
        active_indices = core_indices[active_mask]
        n_active = int(active_mask.sum())
        core_reads = int(ns_core.sum())
        read_metrics = summarize_candidate_reads(mat_all, mat_core, active_mask)

    if not read_metrics:
        # Defensive fallback for programmatic callers constructing an ORFRow
        # with prepared counts but without the public-schema read summary.
        phase_reads = counts.sum(axis=0) if len(counts) else np.zeros(3, dtype=int)
        read_metrics = {
            "n_total_orf_codons_including_stop": n_total_codons,
            "n_core_codons": n_core_codons,
            "n_active_core_codons": n_active,
            "orf_region_reads": core_reads,
            "core_reads": core_reads,
            "analyzed_core_reads": core_reads,
        }
        for phase in range(3):
            observed = int(phase_reads[phase])
            read_metrics[f"observed_phase{phase}_core_reads"] = observed
            read_metrics[f"observed_phase{phase}_core_fraction"] = (
                float(observed) / float(core_reads) if core_reads else 0.0
            )
    out.update(read_metrics)
    out.update(active_core_breadth_metrics(n_active, n_core_codons, args))
    out.update(target_residual_breadth_metrics(counts, pi_host, A0, overlap_type, args))

    if n_core_codons < args.min_core_codons or n_active < args.min_active_core_codons or core_reads < args.min_core_reads:
        out["classification_pre_fdr"] = "insufficient_data"
        out["p_final"] = 1.0
        return out

    pi_obs = counts.sum(axis=0).astype(float)
    pi_obs /= pi_obs.sum()
    out.update({"pi_obs_0": float(pi_obs[0]), "pi_obs_1": float(pi_obs[1]), "pi_obs_2": float(pi_obs[2])})
    out.update(geometry_metrics(pi_obs, pi_host, pi_trans, overlap_type, args))

    lambda_hat, ll0, ll1, stat, p_asym = fit_lambda_lrt(counts, pi_host, pi_trans, A0, grid_size=args.lambda_grid_size)
    lambda_ci_low, lambda_ci_high = lambda_profile_likelihood_interval(
        counts,
        pi_host,
        pi_trans,
        A0,
        lambda_hat,
        ll1,
    )
    ll0_reduced = dm_loglik_matrix(counts, pi_host, A0, include_multinomial=False)
    ll1_reduced = dm_loglik_matrix(counts, pi_mix(lambda_hat, pi_host, pi_trans), A0, include_multinomial=False)
    out.update({
        "lambda_hat": lambda_hat,
        "lambda_profile_ci95_low": lambda_ci_low,
        "lambda_profile_ci95_high": lambda_ci_high,
        "lambda_profile_ci_method": "likelihood_ratio_chi2_1df_95pct",
        "loglik_h0": ll0,
        "loglik_h1": ll1,
        "loglik_reduced_h0": ll0_reduced,
        "loglik_reduced_h1": ll1_reduced,
        "lrt_stat": stat,
        "p_asym": p_asym,
        "bootstrap_gate_pass": int(p_asym < args.bootstrap_gate_p),
        "review_near_bootstrap_gate": int(abs(p_asym - args.bootstrap_gate_p) <= args.review_gate_window),
    })
    out.update(
        model_expected_component_reads(
            core_reads, lambda_hat, pi_host, pi_trans
        )
    )

    pi_fit = pi_mix(lambda_hat, pi_host, pi_trans)
    direction = pi_trans - pi_host
    idx, scalar_resid = projected_residuals(counts, active_indices, pi_fit, direction)
    lag1, lag1_pairs = lag1_for_consecutive_codons(idx, scalar_resid)
    out["lag1_residual_autocorrelation"] = lag1
    out["lag1_consecutive_pairs"] = lag1_pairs

    if p_asym >= args.bootstrap_gate_p:
        out["bootstrap_method"] = "not_run"
        out["p_final"] = 1.0
        out["classification_pre_fdr"] = "host_only_supported"
        return out

    p_iid = iid_parametric_bootstrap_p(
        counts, pi_host, pi_trans, A0, stat, args.bootstrap_reps, rng, grid_size=args.lambda_grid_size
    )
    out["p_iid_boot"] = p_iid
    iid_exceedances = int(round(p_iid * (args.bootstrap_reps + 1.0) - 1.0))
    out["iid_boot_exceedances"] = iid_exceedances
    iid_component_p = p_iid
    methods = ["iid_dm"]

    run_importance = bool(
        args.importance_execution_policy == "always"
        or (
            args.importance_execution_policy == "adaptive"
            and iid_exceedances < args.importance_iid_exceedance_threshold
        )
    )
    if run_importance:
        if args.importance_mode_used == "fast":
            importance = two_stage_importance_sampling_bootstrap_p(
                counts,
                pi_host,
                pi_trans,
                A0,
                stat,
                lambda_hat,
                args.importance_reps,
                args.importance_pilot_reps,
                args.importance_confirm_min_reps,
                args.importance_allocation_safety_factor,
                args.importance_min_tail_ess,
                args.importance_max_relative_se,
                rng,
                args.importance_etas_parsed,
                grid_size=args.lambda_grid_size,
            )
        else:
            importance = importance_sampling_bootstrap_p(
                counts,
                pi_host,
                pi_trans,
                A0,
                stat,
                lambda_hat,
                args.importance_reps,
                rng,
                args.importance_etas_parsed,
                grid_size=args.lambda_grid_size,
            )
        out.update(importance)
        p_importance = safe_float(importance.get("p_importance"), float("nan"))
        tail_ess = safe_float(importance.get("importance_tail_ess"), 0.0)
        relative_se = safe_float(importance.get("p_importance_relative_se"), float("inf"))
        weight_mean = safe_float(importance.get("importance_weight_mean"), float("nan"))
        usable = bool(
            np.isfinite(p_importance)
            and p_importance > 0.0
            and tail_ess >= args.importance_min_tail_ess
            and relative_se <= args.importance_max_relative_se
            and np.isfinite(weight_mean)
            and 0.5 <= weight_mean <= 1.5
        )
        out["importance_diagnostic_pass"] = int(usable)
        if not np.isfinite(p_importance) or p_importance <= 0.0:
            out["importance_status"] = "failed_no_weighted_tail"
        elif not 0.5 <= weight_mean <= 1.5:
            out["importance_status"] = "failed_weight_mean"
        elif tail_ess < args.importance_min_tail_ess:
            out["importance_status"] = "failed_low_tail_ess"
        elif relative_se > args.importance_max_relative_se:
            out["importance_status"] = "failed_high_relative_se"
        else:
            out["importance_status"] = "pass"
        methods.append(
            "importance_dm_fast_two_stage"
            if args.importance_mode_used == "fast"
            else "importance_dm_accurate_fixed"
        )
        if args.importance_use_for_p_final and usable:
            iid_component_p = p_importance
            out["importance_used_for_p_final"] = 1
        else:
            out["importance_used_for_p_final"] = 0
    elif args.importance_execution_policy == "adaptive":
        out["importance_status"] = "not_needed_iid_tail_resolved"
        out["importance_used_for_p_final"] = 0

    robust_ps = [iid_component_p]

    high_lag = bool(
        not args.disable_block_bootstrap
        and n_active >= args.min_active_for_lag1
        and np.isfinite(lag1)
        and lag1 > args.lag1_threshold
    )

    if high_lag:
        for block_size in args.block_sizes_parsed:
            p_block = residual_block_bootstrap_p(
                counts,
                active_indices,
                pi_host,
                pi_trans,
                A0,
                stat,
                args.bootstrap_reps,
                block_size,
                rng,
                grid_size=args.lambda_grid_size,
            )
            out[f"p_block{block_size}_boot"] = p_block
            if p_block is not None:
                robust_ps.append(float(p_block))
                methods.append(f"residual_block{block_size}")

    p_robust = max(robust_ps)
    out["bootstrap_method"] = "+".join(methods)
    out["p_boot_robust"] = p_robust
    out["p_final"] = p_robust
    out["classification_pre_fdr"] = "tested"
    return out


