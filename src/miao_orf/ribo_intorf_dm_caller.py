"""
intORF DM mixture caller
========================

Purpose
-------
Detect an additional ORF-like Ribo-seq P-site component inside annotated CDS
regions for out-of-frame internal ORFs (intORF_altframe).

The script consumes the IGV-friendly *.torf.tsv files generated by
orf_scan_transcriptome.py and a sorted/indexed 1-nt P-site BAM.

Model
-----
1. Load a validated QC background, or learn a sample-level canonical translation
   template from high-quality MANE CDS when no background file is supplied:
       pi_trans = (pi0, pi1, pi2)
       A0       = global Dirichlet-multinomial concentration

2. Re-index every intORF codon in the intORF's own coordinate system.
   If the intORF is shifted by one nucleotide relative to the host CDS (F1):
       c_j = (x[h,1], x[h,2], x[h+1,0])
       pi_host = (pi1, pi2, pi0)
   If shifted by two nucleotides (F2):
       c_j = (x[h,2], x[h+1,0], x[h+1,1])
       pi_host = (pi2, pi0, pi1)

   In practice, re-indexing is achieved directly by mapping P-sites to the
   candidate intORF blocks and using intORF-relative coordinates.

3. Fit the single-parameter model with fixed A=A0:
       pi_mix(lambda) = (1-lambda) * pi_host + lambda * pi_trans
       c_j ~ DM(n_j, A0 * pi_mix(lambda))

       H0: lambda = 0
       H1: lambda > 0

   lambda is interpreted as the estimated fraction of overlap-region P-site
   reads contributed by the intORF-like component, not as replacement of host
   CDS translation.

4. Calculate a boundary-corrected asymptotic LRT p-value for all eligible
   candidates. Run H0 parametric bootstrap only for candidates passing a
   configurable asymptotic gate. Apply BH and BY FDR correction separately to
   the primary-length and ultra-short exploratory candidate families.
   Candidates not entering bootstrap receive p_final=1, while p_asym is
   retained for review.

5. Report geometry diagnostics:
       lambda_gain, lambda_drop, lambda_proj,
       distance_to_mixture_segment,
       lag1_residual_autocorrelation.

6. Final credible calls must also have broad target-frame residual support:
       target_vs_unused_z05_codons / active_core_codons > 1/3
   Candidates that pass DM significance, geometry, and active-core breadth but
   fail this final pattern requirement remain in the output as
   low_target_frame_residual_breadth.

7. Length is a reporting tier rather than a silent discard. Candidates below
   --primary-min-intorf-aa remain analyzable down to --min-intorf-aa, but an
   otherwise credible call is labelled ultra_short_exploratory and is excluded
   from the primary credible count.

Optional moving-block residual bootstrap sensitivity analysis is run for
candidates with sufficiently many active core codons and elevated lag-1
residual autocorrelation.

Inputs
------
  --psite-bam     sorted + indexed 1-nt P-site BAM
  --torf          one *.torf.tsv, a directory, or a glob/prefix
  --out-prefix    output prefix
  --dm-background optional validated background from ribo_metagene_qc.py

Primary outputs
---------------
  <out>.template.tsv
  <out>.intorf_dm_results.tsv
  <out>.summary.tsv
  <out>.prefilter_summary.tsv
  <out>.run_manifest.json

Dependencies
------------
  Python >= 3.9, pysam, numpy, scipy

Release metadata
----------------
  Program: miao-orf-intorf-dm
  Version: 1.0.0
  Author: Haomiao Su
  Contact: suhaomiao@csu.edu.cn
"""

