FDR_EXCLUDED_CLASSIFICATIONS = frozenset({
    "invalid_overlap_type",
    "too_short",
    "insufficient_data",
    "template_separation_too_small",
})

PRIMARY_FDR_FAMILY = "primary"
EXPLORATORY_FDR_FAMILY = "ultra_short_exploratory"
EXCLUDED_FDR_FAMILY = "excluded"
PRIMARY_CREDIBLE_CLASS = "credible_extra_ORF_like_signal"
EXPLORATORY_CREDIBLE_CLASS = "ultra_short_exploratory"


def candidate_length_tier(out: Dict[str, object], args: argparse.Namespace) -> str:
    peptide_len = safe_int(out.get("peptide_len", out.get("aa_len", 0)), 0)
    if peptide_len < args.primary_min_intorf_aa:
        return EXPLORATORY_FDR_FAMILY
    return PRIMARY_FDR_FAMILY


def adjust_bh(pvalues: Sequence[float]) -> np.ndarray:
    p = np.asarray(pvalues, dtype=float)
    m = len(p)
    if m == 0:
        return np.array([], dtype=float)
    order = np.argsort(p)
    ranked = p[order]
    adj = ranked * m / np.arange(1, m + 1)
    adj = np.minimum.accumulate(adj[::-1])[::-1]
    out = np.empty(m, dtype=float)
    out[order] = np.minimum(adj, 1.0)
    return out


def adjust_by(pvalues: Sequence[float]) -> np.ndarray:
    p = np.asarray(pvalues, dtype=float)
    m = len(p)
    if m == 0:
        return np.array([], dtype=float)
    harmonic = float(np.sum(1.0 / np.arange(1, m + 1)))
    return np.minimum(adjust_bh(p) * harmonic, 1.0)


def finalize_classification(out: Dict[str, object], args: argparse.Namespace) -> str:
    pre = str(out.get("classification_pre_fdr", ""))
    if pre in FDR_EXCLUDED_CLASSIFICATIONS:
        return pre

    q_bh = safe_float(out.get("q_BH", 1.0), 1.0)
    if q_bh >= args.fdr_threshold:
        return "host_only_supported"

    effect_geometry_ok = bool(
        safe_float(out.get("lambda_hat", float("nan"))) > args.lambda_min
        and safe_float(out.get("alt_frame_gain", float("nan"))) > 0
        and safe_float(out.get("host_frame_drop", float("nan"))) < 0
        and safe_int(out.get("mixture_geometry_consistent", 0), 0) == 1
        and safe_float(out.get("distance_to_mixture_segment", float("inf")), float("inf")) < args.distance_to_segment_max
    )
    if not effect_geometry_ok:
        return "atypical_pattern"
    if safe_int(out.get("credible_active_core_breadth_ok", 0), 0) != 1:
        return "localized_core_signal"
    if safe_int(out.get("credible_target_residual_breadth_ok", 0), 0) != 1:
        return "low_target_frame_residual_breadth"
    if str(out.get("length_tier", "")) == EXPLORATORY_FDR_FAMILY:
        return EXPLORATORY_CREDIBLE_CLASS
    return PRIMARY_CREDIBLE_CLASS


def negative_log10_score(value: object) -> float:
    """Convert a p/q value into a finite, monotonically increasing score."""
    numeric = safe_float(value, 1.0)
    if not math.isfinite(numeric):
        return 0.0
    return float(-math.log10(min(1.0, max(numeric, 1e-300))))


def add_output_qc_contract(out: Dict[str, object]) -> None:
    """Add compact, user-facing QC fields without changing call decisions."""
    out["dm_evidence_score"] = negative_log10_score(out.get("p_final", 1.0))
    out["dm_fdr_score"] = negative_log10_score(out.get("q_BH", 1.0))

    classification = str(out.get("classification", ""))
    prefilter_reason = str(out.get("prefilter_reason", "")).strip()
    flags: List[str] = []
    if prefilter_reason:
        flags.append(prefilter_reason)

    lambda_hat = safe_float(out.get("lambda_hat"), float("nan"))
    fitted = math.isfinite(lambda_hat)
    if not fitted:
        pre = str(out.get("classification_pre_fdr", "")).strip()
        if pre and pre not in {"host_only_supported", "tested"} and pre not in flags:
            flags.append(pre)
        out["qc_status"] = "not_evaluable"
        out["background_template_sensitivity_status"] = "not_evaluable"
    else:
        if safe_int(out.get("template_separation_ok", 0), 0) != 1:
            flags.append("template_separation")
        if safe_int(out.get("mixture_geometry_consistent", 0), 0) != 1:
            flags.append("mixture_geometry")
        if safe_int(out.get("credible_active_core_breadth_ok", 0), 0) != 1:
            flags.append("active_core_breadth")
        if safe_int(out.get("credible_target_residual_breadth_ok", 0), 0) != 1:
            flags.append("target_residual_breadth")
        importance_status = str(out.get("importance_status", ""))
        if importance_status.startswith("failed_"):
            flags.append(importance_status)
        out["qc_status"] = "pass" if not flags else "flagged"
        out["background_template_sensitivity_status"] = (
            "pass"
            if safe_int(out.get("mixture_geometry_consistent", 0), 0) == 1
            else "flagged"
        )

    out["qc_flags"] = "|".join(dict.fromkeys(flags))
    out["filter_reason"] = (
        ""
        if classification in {PRIMARY_CREDIBLE_CLASS, EXPLORATORY_CREDIBLE_CLASS}
        else (prefilter_reason or classification)
    )


def apply_fdr_and_classification(results: Sequence[Dict[str, object]], args: argparse.Namespace) -> None:
    """Adjust primary and exploratory hypotheses separately and retain all rows."""
    for row in results:
        row["length_tier"] = candidate_length_tier(row, args)
        row["fdr_family"] = EXCLUDED_FDR_FAMILY
        row["q_BH"] = 1.0
        row["q_BY"] = 1.0

    for family in (PRIMARY_FDR_FAMILY, EXPLORATORY_FDR_FAMILY):
        family_indices = [
            i
            for i, row in enumerate(results)
            if str(row.get("classification_pre_fdr", "")) not in FDR_EXCLUDED_CLASSIFICATIONS
            and str(row.get("length_tier", "")) == family
        ]
        family_p_final = [
            safe_float(results[i].get("p_final", 1.0), 1.0)
            for i in family_indices
        ]
        family_q_bh = adjust_bh(family_p_final)
        family_q_by = adjust_by(family_p_final)
        for i, bh, by in zip(family_indices, family_q_bh, family_q_by):
            results[i]["fdr_family"] = family
            results[i]["q_BH"] = float(bh)
            results[i]["q_BY"] = float(by)

    for row in results:
        row["classification"] = finalize_classification(row, args)
        row["primary_credible_call"] = int(row["classification"] == PRIMARY_CREDIBLE_CLASS)
        row["ultra_short_exploratory_call"] = int(row["classification"] == EXPLORATORY_CREDIBLE_CLASS)
        add_output_qc_contract(row)


