def fmt(x: object) -> str:
    if x is None:
        return ""
    if isinstance(x, (float, np.floating)):
        if not np.isfinite(float(x)):
            return ""
        return f"{float(x):.10g}"
    return str(x)


def list_input_torfs(spec: str) -> List[str]:
    if any(ch in spec for ch in "*?"):
        files = sorted(glob.glob(spec))
    elif os.path.isdir(spec):
        files = sorted(glob.glob(os.path.join(spec, "*.torf.tsv")))
    elif os.path.isfile(spec):
        files = [spec]
    else:
        files = sorted(glob.glob(f"{spec}.*.torf.tsv"))
    if not files:
        raise SystemExit(f"ERROR: no tORF TSV files found for --torf {spec!r}")
    return files


def load_dm_background(path: str, args: argparse.Namespace) -> Tuple[np.ndarray, float, Dict[str, object]]:
    """Load and validate a metagene-QC DM background file."""
    if not os.path.isfile(path):
        raise SystemExit(f"ERROR: DM background not found: {path}")

    values: Dict[str, str] = {}
    with open(path, "r", encoding="utf-8") as handle:
        reader = csv.DictReader(handle, delimiter="\t")
        fields = set(reader.fieldnames or [])
        key_field = "metric" if "metric" in fields else "parameter" if "parameter" in fields else None
        if key_field is None or "value" not in fields:
            raise SystemExit(
                f"ERROR: DM background must contain metric/parameter and value columns: {path}"
            )
        for row in reader:
            key = str(row.get(key_field, "")).strip()
            if not key:
                continue
            if key in values:
                raise SystemExit(f"ERROR: duplicate DM background parameter {key!r} in {path}")
            values[key] = str(row.get("value", "")).strip()

    required = {"pi0", "pi1", "pi2", "A"}
    missing = sorted(required - set(values))
    if missing:
        raise SystemExit(f"ERROR: DM background missing parameters in {path}: {', '.join(missing)}")

    status = values.get("template_status", "success")
    if status != "success":
        raise SystemExit(f"ERROR: DM background template_status is {status!r}, not 'success': {path}")

    try:
        pi = np.asarray([float(values[f"pi{i}"]) for i in range(3)], dtype=float)
        A0 = float(values["A"])
    except ValueError as exc:
        raise SystemExit(f"ERROR: non-numeric pi/A parameter in DM background {path}: {exc}") from exc
    if not np.all(np.isfinite(pi)) or np.any(pi <= 0):
        raise SystemExit(f"ERROR: DM background pi values must be finite and > 0: {pi.tolist()}")
    pi_sum = float(pi.sum())
    if abs(pi_sum - 1.0) > 1e-6:
        raise SystemExit(f"ERROR: DM background pi values sum to {pi_sum:.10g}, expected 1: {path}")
    pi = pi / pi_sum
    if not math.isfinite(A0) or A0 <= 0:
        raise SystemExit(f"ERROR: DM background A must be finite and > 0: {A0!r}")
    if A0 < args.min_a0:
        raise SystemExit(
            f"ERROR: DM background A0={A0:.10g} is below --min-a0={args.min_a0:.10g}; "
            "intORF inference is disabled for this background"
        )

    source_method = values.get("pi_method", values.get("pi_method_used", ""))
    if source_method and source_method != args.pi_method:
        raise SystemExit(
            f"ERROR: DM background pi_method={source_method!r} does not match --pi-method={args.pi_method!r}"
        )
    source_rl = values.get("rl_filter", "")
    requested_rl = str(args.rl) if args.rl is not None else "pooled"
    if source_rl and source_rl != requested_rl:
        raise SystemExit(
            f"ERROR: DM background rl_filter={source_rl!r} does not match caller RL setting {requested_rl!r}"
        )
    source_bam = values.get("psite_bam", "")
    if source_bam and os.path.realpath(source_bam) != os.path.realpath(args.psite_bam):
        raise SystemExit(
            f"ERROR: DM background was estimated from a different P-site BAM: "
            f"background={source_bam!r}, caller={os.path.abspath(args.psite_bam)!r}"
        )

    def optional_vector(prefix: str) -> np.ndarray:
        keys = [f"{prefix}_{i}" for i in range(3)]
        if all(key in values and values[key] != "" for key in keys):
            try:
                return np.asarray([float(values[key]) for key in keys], dtype=float)
            except ValueError:
                pass
        return np.full(3, np.nan, dtype=float)

    info: Dict[str, object] = {
        "pi_read_weighted": optional_vector("pi_read_weighted"),
        "pi_codon_equal": optional_vector("pi_codon_equal"),
        "pi_trimmed": optional_vector("pi_trimmed"),
        "pi_used": pi,
        "A0": A0,
        "alpha0": A0 * pi,
        "template_cds_seen": safe_int(values.get("template_cds_seen", 0), 0),
        "template_cds_kept": safe_int(values.get("template_cds_kept", 0), 0),
        "template_codons": safe_int(values.get("template_codons", 0), 0),
        "template_patterns": safe_int(values.get("template_unique_patterns", 0), 0),
        "trim_reservoir_n": safe_int(values.get("trim_reservoir_n", 0), 0),
        "template_status": "success",
        "background_source": "qc_file",
        "background_path": os.path.abspath(path),
        "background_pi_method": source_method or args.pi_method,
        "background_psite_bam": source_bam,
    }
    return pi, A0, info


def parse_blocks_01(block_sizes: str, genomic_starts1: str) -> List[Tuple[int, int]]:
    sizes = [int(x) for x in str(block_sizes).split(",") if x != ""]
    starts1 = [int(x) for x in str(genomic_starts1).split(",") if x != ""]
    if not sizes or len(sizes) != len(starts1):
        return []
    return [(s1 - 1, s1 - 1 + size) for s1, size in zip(starts1, sizes)]


def bam_strand(read: pysam.AlignedSegment) -> str:
    return "-" if read.is_reverse else "+"


def read_has_rl(read: pysam.AlignedSegment, rl: Optional[int], rl_source: str = "auto") -> bool:
    """Apply an optional read-length filter without silently dropping all reads.

    For a 1-nt P-site BAM, ``query_length`` is usually 1 and cannot recover the
    original RPF length. Such BAMs should carry an ``RL`` tag if --rl filtering
    is requested. ``auto`` prefers RL and falls back to query_length only when
    the tag is absent.
    """
    if rl is None:
        return True
    if rl_source == "tag":
        try:
            return int(read.get_tag("RL")) == rl
        except KeyError:
            return False
    if rl_source == "query_length":
        return int(read.query_length or 0) == rl
    if rl_source != "auto":
        raise ValueError(f"Unsupported rl_source: {rl_source}")
    try:
        return int(read.get_tag("RL")) == rl
    except KeyError:
        return int(read.query_length or 0) == rl


def validate_rl_filter_source(bam_path: str, rl: Optional[int], rl_source: str, max_reads: int = 5000) -> None:
    """Fail fast for impossible --rl configurations and report the chosen source."""
    if rl is None:
        return
    bam = pysam.AlignmentFile(bam_path, "rb")
    seen = 0
    n_rl_tag = 0
    n_tag_match = 0
    qlens = Counter()
    try:
        for read in bam.fetch(until_eof=True):
            if read.is_unmapped:
                continue
            seen += 1
            qlen = int(read.query_length or 0)
            qlens[qlen] += 1
            try:
                tag_value = int(read.get_tag("RL"))
                n_rl_tag += 1
                if tag_value == rl:
                    n_tag_match += 1
            except KeyError:
                pass
            if seen >= max_reads:
                break
    finally:
        bam.close()

    if seen == 0:
        raise SystemExit("ERROR: BAM contains no mapped alignments during --rl validation")

    qlen_match = qlens.get(int(rl), 0)
    qlen_summary = ",".join(f"{k}:{v}" for k, v in qlens.most_common(8))
    sys.stderr.write(
        f"[rl] source={rl_source}, requested={rl}, sampled_reads={seen:,}, "
        f"RL_tags={n_rl_tag:,}, RL_matches={n_tag_match:,}, "
        f"query_length_matches={qlen_match:,}, query_lengths={qlen_summary}\n"
    )

    if rl_source == "tag" and n_rl_tag == 0:
        raise SystemExit("ERROR: --rl-source tag requested, but sampled BAM reads have no RL tag")
    if rl_source == "query_length" and qlen_match == 0:
        raise SystemExit("ERROR: --rl-source query_length requested, but sampled BAM reads do not match --rl")
    if rl_source == "auto" and n_tag_match == 0 and qlen_match == 0:
        if n_rl_tag == 0 and set(qlens).issubset({0, 1}) and int(rl) != 1:
            raise SystemExit(
                "ERROR: --rl filtering cannot recover original RPF length from this apparent 1-nt P-site BAM: "
                "sampled reads have no RL tag and query_length is 1. Recreate the P-site BAM with RL tags, "
                "or omit --rl to analyze pooled read lengths."
            )
        raise SystemExit(
            "ERROR: no sampled BAM reads match the requested --rl value under --rl-source auto. "
            "Check whether read length is stored in the RL tag or query_length."
        )


def project_to_simplex(v: np.ndarray) -> np.ndarray:
    """Euclidean projection of a real vector onto the probability simplex."""
    x = np.asarray(v, dtype=float)
    if x.ndim != 1:
        raise ValueError("simplex projection expects a vector")
    u = np.sort(x)[::-1]
    cssv = np.cumsum(u)
    rho_idx = np.where(u * np.arange(1, len(u) + 1) > (cssv - 1.0))[0]
    if len(rho_idx) == 0:
        return np.full_like(x, 1.0 / len(x))
    rho = int(rho_idx[-1])
    theta = (cssv[rho] - 1.0) / float(rho + 1)
    w = np.maximum(x - theta, 0.0)
    s = w.sum()
    return w / s if s > 0 else np.full_like(x, 1.0 / len(x))


