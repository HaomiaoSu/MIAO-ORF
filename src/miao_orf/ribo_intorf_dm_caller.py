def dm_loglik_matrix(counts: np.ndarray, pi: np.ndarray, A0: float, include_multinomial: bool = True) -> float:
    """Dirichlet-multinomial log-likelihood for codon count triplets.

    The multinomial coefficient is part of the standard DM probability mass
    function. It cancels exactly in the within-dataset H0/H1 LRT, but is kept
    by default so reported absolute log-likelihoods remain comparable with
    standard DM implementations. Set include_multinomial=False to obtain a
    reduced log-likelihood useful for debugging.
    """
    if counts.size == 0:
        return 0.0
    pi = np.clip(np.asarray(pi, dtype=float), 1e-12, 1.0)
    pi = pi / pi.sum()
    alpha = A0 * pi
    n = counts.sum(axis=1)
    core = (
        gammaln(A0)
        - gammaln(n + A0)
        + np.sum(gammaln(counts + alpha) - gammaln(alpha), axis=1)
    )
    if include_multinomial:
        core = core + gammaln(n + 1) - np.sum(gammaln(counts + 1), axis=1)
    return float(np.sum(core))


def pi_mix(lambda_value: float, pi_host: np.ndarray, pi_trans: np.ndarray) -> np.ndarray:
    return (1.0 - lambda_value) * pi_host + lambda_value * pi_trans


def model_expected_component_reads(
    core_reads: int,
    lambda_hat: float,
    pi_host: np.ndarray,
    pi_trans: np.ndarray,
) -> Dict[str, float]:
    """Return fractional, model-expected host-CDS and intORF core P-site counts.

    These values summarize the fitted mixture; they are not read-level source
    assignments.  Phase indices are in the candidate intORF coordinate system,
    matching ``pi_host_*``, ``pi_trans_*``, and ``pi_obs_*`` in the output.
    """
    total = float(core_reads)
    lam = float(lambda_hat)
    host = np.asarray(pi_host, dtype=float)
    trans = np.asarray(pi_trans, dtype=float)
    if not np.isfinite(total) or total < 0.0:
        raise ValueError("core_reads must be finite and non-negative")
    if not np.isfinite(lam) or not 0.0 <= lam <= 1.0:
        raise ValueError("lambda_hat must be finite and in [0, 1]")
    if host.shape != (3,) or trans.shape != (3,):
        raise ValueError("pi_host and pi_trans must each contain three phases")
    if (
        not np.all(np.isfinite(host))
        or not np.all(np.isfinite(trans))
        or np.any(host < 0.0)
        or np.any(trans < 0.0)
        or float(host.sum()) <= 0.0
        or float(trans.sum()) <= 0.0
    ):
        raise ValueError("phase templates must be finite, non-negative, and non-empty")

    # dm_loglik_matrix normalizes phase probabilities before evaluating the
    # likelihood. Normalize here as well so expected phase counts exactly sum
    # to their component totals even if a loaded template has rounding error.
    host = host / host.sum()
    trans = trans / trans.sum()
    host_total = total * (1.0 - lam)
    intorf_total = total * lam
    out = {
        "model_expected_host_cds_fraction": 1.0 - lam,
        "model_expected_intorf_fraction": lam,
        "model_expected_host_cds_core_reads": host_total,
        "model_expected_intorf_core_reads": intorf_total,
    }
    for phase in range(3):
        out[f"model_expected_host_cds_phase{phase}_core_reads"] = (
            host_total * float(host[phase])
        )
        out[f"model_expected_intorf_phase{phase}_core_reads"] = (
            intorf_total * float(trans[phase])
        )
    return out


def lambda_profile_likelihood_interval(
    counts: np.ndarray,
    pi_host: np.ndarray,
    pi_trans: np.ndarray,
    A0: float,
    lambda_hat: float,
    loglik_h1: float,
    confidence_level: float = LAMBDA_PROFILE_CI_LEVEL,
) -> Tuple[float, float]:
    """Return a bounded likelihood-ratio profile interval for ``lambda``.

    The interval contains lambda values whose profile log-likelihood remains
    within the usual chi-square(1) likelihood-ratio cutoff.  It quantifies
    uncertainty in the fitted mixture fraction; it is not a Bayesian credible
    interval and does not assign individual reads to either component.
    """
    if not 0.0 < confidence_level < 1.0:
        raise ValueError("confidence_level must be in (0, 1)")
    lam = float(lambda_hat)
    if not math.isfinite(lam) or not 0.0 <= lam <= 1.0:
        raise ValueError("lambda_hat must be finite and in [0, 1]")
    cutoff = float(loglik_h1) - 0.5 * float(chi2.ppf(confidence_level, df=1))

    def support(value: float) -> float:
        return dm_loglik_matrix(
            counts,
            pi_mix(float(value), pi_host, pi_trans),
            A0,
        ) - cutoff

    mle_support = support(lam)
    if not math.isfinite(mle_support) or mle_support < -1e-7:
        raise RuntimeError("profile-likelihood interval does not contain lambda_hat")

    support_zero = support(0.0)
    if support_zero >= 0.0 or lam <= 0.0:
        lower = 0.0
    else:
        lower = float(brentq(support, 0.0, lam, xtol=1e-7, rtol=1e-10))

    support_one = support(1.0)
    if support_one >= 0.0 or lam >= 1.0:
        upper = 1.0
    else:
        upper = float(brentq(support, lam, 1.0, xtol=1e-7, rtol=1e-10))
    return lower, upper


def fit_lambda_lrt(
    counts: np.ndarray,
    pi_host: np.ndarray,
    pi_trans: np.ndarray,
    A0: float,
    grid_size: int = 101,
) -> Tuple[float, float, float, float, float]:
    """Fit lambda robustly with a coarse global grid followed by local refinement."""
    ll0 = dm_loglik_matrix(counts, pi_host, A0)

    def objective(lam: float) -> float:
        return -dm_loglik_matrix(counts, pi_mix(float(lam), pi_host, pi_trans), A0)

    grid_size = max(3, int(grid_size))
    grid = np.linspace(0.0, 1.0, grid_size)
    grid_obj = np.asarray([objective(float(lam)) for lam in grid], dtype=float)
    best_idx = int(np.nanargmin(grid_obj))
    candidates: List[Tuple[float, float]] = [
        (float(grid[best_idx]), float(grid_obj[best_idx])),
        (0.0, float(grid_obj[0])),
        (1.0, float(grid_obj[-1])),
    ]

    left = float(grid[max(0, best_idx - 1)])
    right = float(grid[min(grid_size - 1, best_idx + 1)])
    if right - left > 1e-12:
        fit = minimize_scalar(
            objective,
            bounds=(left, right),
            method="bounded",
            options={"xatol": 1e-8, "maxiter": 150},
        )
        if fit.success and np.isfinite(fit.fun):
            candidates.append((float(np.clip(fit.x, 0.0, 1.0)), float(fit.fun)))

    lambda_hat, best_obj = min(candidates, key=lambda pair: pair[1])
    ll1 = float(-best_obj)
    stat = max(0.0, 2.0 * (ll1 - ll0))
    p_asym = 1.0 if stat <= 1e-14 else float(0.5 * chi2.sf(stat, df=1))
    return float(lambda_hat), ll0, ll1, stat, p_asym


def simulate_dm_counts(ns: np.ndarray, pi: np.ndarray, A0: float, rng: np.random.Generator) -> np.ndarray:
    alpha = A0 * np.asarray(pi, dtype=float)
    out = np.zeros((len(ns), 3), dtype=int)
    for i, n in enumerate(ns):
        p = rng.dirichlet(alpha)
        out[i] = rng.multinomial(int(n), p)
    return out


def iid_parametric_bootstrap_p(
    counts: np.ndarray,
    pi_host: np.ndarray,
    pi_trans: np.ndarray,
    A0: float,
    observed_stat: float,
    reps: int,
    rng: np.random.Generator,
    grid_size: int = 101,
) -> float:
    ns = counts.sum(axis=1)
    ge = 0
    for _ in range(reps):
        sim = simulate_dm_counts(ns, pi_host, A0, rng)
        _, _, _, stat_b, _ = fit_lambda_lrt(sim, pi_host, pi_trans, A0, grid_size=grid_size)
        if stat_b >= observed_stat - 1e-12:
            ge += 1
    return (1.0 + ge) / (reps + 1.0)


def importance_sampling_bootstrap_p(
    counts: np.ndarray,
    pi_host: np.ndarray,
    pi_trans: np.ndarray,
    A0: float,
    observed_stat: float,
    observed_lambda: float,
    reps: int,
    rng: np.random.Generator,
    eta_values: Sequence[float],
    grid_size: int = 101,
) -> Dict[str, object]:
    """Estimate the original H0 tail with a mixture importance sampler.

    Each proposal remains on the biologically defined host-to-translation
    segment.  A complete candidate matrix is drawn from one proposal component
    and reweighted by P_H0(X) / sum_k w_k P_eta_k(X).  The estimator therefore
    targets exactly the same candidate-specific H0 as the iid DM bootstrap; no
    spike-in labels or fitted noise component enter the calculation.

    This function deliberately returns diagnostics rather than hiding unstable
    rare-event estimates behind a single p-value.
    """
    requested = [float(value) for value in eta_values]
    requested.extend([0.0, 0.5 * float(observed_lambda), float(observed_lambda)])
    etas = sorted({round(float(np.clip(value, 0.0, 1.0)), 12) for value in requested})
    if observed_stat <= 1e-14:
        # The one-sided LRT is nonnegative by construction, so P_H0(T >= 0)=1
        # exactly. Estimating this identity with importance weights only adds
        # Monte Carlo noise and wastes most of the cost for boundary fits.
        return {
            "p_importance": 1.0,
            "p_importance_mc_se": 0.0,
            "p_importance_relative_se": 0.0,
            "importance_total_reps_used": 0,
            "importance_tail_exceedances": reps,
            "importance_tail_ess": float(reps),
            "importance_max_tail_weight_frac": 1.0 / float(reps),
            "importance_weight_mean": 1.0,
            "importance_weight_ess": float(reps),
            "importance_proposal_etas": ",".join(f"{eta:.12g}" for eta in etas),
            "importance_component_draws": "exact_lrt_zero",
            "importance_component_tail_draws": "exact_lrt_zero",
        }

    ns = counts.sum(axis=1)
    proposal_pis = [pi_mix(eta, pi_host, pi_trans) for eta in etas]
    n_components = len(proposal_pis)
    log_component_weight = -math.log(float(n_components))

    weights = np.zeros(reps, dtype=float)
    tail_terms = np.zeros(reps, dtype=float)
    exceedances = 0
    component_draws = np.zeros(n_components, dtype=int)
    component_tail_draws = np.zeros(n_components, dtype=int)

    for rep in range(reps):
        component = int(rng.integers(0, n_components))
        component_draws[component] += 1
        sim = simulate_dm_counts(ns, proposal_pis[component], A0, rng)
        _, _, _, stat_b, _ = fit_lambda_lrt(
            sim, pi_host, pi_trans, A0, grid_size=grid_size
        )

        log_p0 = dm_loglik_matrix(sim, pi_host, A0)
        log_components = np.asarray(
            [
                log_component_weight + dm_loglik_matrix(sim, proposal_pi, A0)
                for proposal_pi in proposal_pis
            ],
            dtype=float,
        )
        log_q = float(np.logaddexp.reduce(log_components))
        log_weight = float(log_p0 - log_q)
        weight = 0.0 if log_weight < -745.0 else float(math.exp(min(log_weight, 709.0)))
        weights[rep] = weight

        if stat_b >= observed_stat - 1e-12:
            exceedances += 1
            component_tail_draws[component] += 1
            tail_terms[rep] = weight

    p_hat_raw = float(np.mean(tail_terms))
    p_hat = float(np.clip(p_hat_raw, 0.0, 1.0))
    se = float(np.std(tail_terms, ddof=1) / math.sqrt(reps)) if reps > 1 else float("nan")
    rel_se = float(se / p_hat_raw) if p_hat_raw > 0.0 and np.isfinite(se) else float("inf")

    weight_sum = float(weights.sum())
    weight_sq_sum = float(np.square(weights).sum())
    weight_ess = (weight_sum * weight_sum / weight_sq_sum) if weight_sq_sum > 0.0 else 0.0
    weight_mean = float(np.mean(weights))

    tail_sum = float(tail_terms.sum())
    tail_sq_sum = float(np.square(tail_terms).sum())
    tail_ess = (tail_sum * tail_sum / tail_sq_sum) if tail_sq_sum > 0.0 else 0.0
    max_tail_fraction = (
        float(np.max(tail_terms) / tail_sum) if tail_sum > 0.0 else float("nan")
    )

    return {
        "p_importance": p_hat if exceedances > 0 else float("nan"),
        "p_importance_mc_se": se,
        "p_importance_relative_se": rel_se,
        "importance_total_reps_used": int(reps),
        "importance_tail_exceedances": exceedances,
        "importance_tail_ess": tail_ess,
        "importance_max_tail_weight_frac": max_tail_fraction,
        "importance_weight_mean": weight_mean,
        "importance_weight_ess": weight_ess,
        "importance_proposal_etas": ",".join(f"{eta:.12g}" for eta in etas),
        "importance_component_draws": ",".join(str(int(value)) for value in component_draws),
        "importance_component_tail_draws": ",".join(str(int(value)) for value in component_tail_draws),
    }


def two_stage_importance_sampling_bootstrap_p(
    counts: np.ndarray,
    pi_host: np.ndarray,
    pi_trans: np.ndarray,
    A0: float,
    observed_stat: float,
    observed_lambda: float,
    max_confirmation_reps: int,
    pilot_reps: int,
    min_confirmation_reps: int,
    allocation_safety_factor: float,
    target_tail_ess: float,
    target_relative_se: float,
    rng: np.random.Generator,
    eta_values: Sequence[float],
    grid_size: int = 101,
) -> Dict[str, object]:
    """Plan an independent importance confirmation sample from a pilot.

    The pilot determines only the confirmation sample size.  Its weighted tail
    terms are deliberately excluded from the reported p-value.  Conditional on
    the pilot, the confirmation estimate therefore remains an ordinary fixed-n
    importance estimate rather than a naively optional-stopped sample mean.
    """
    pilot = importance_sampling_bootstrap_p(
        counts,
        pi_host,
        pi_trans,
        A0,
        observed_stat,
        observed_lambda,
        pilot_reps,
        rng,
        eta_values,
        grid_size=grid_size,
    )

    pilot_rel_se = safe_float(
        pilot.get("p_importance_relative_se"), float("inf")
    )
    pilot_tail_ess = safe_float(pilot.get("importance_tail_ess"), 0.0)
    planned = int(min_confirmation_reps)
    reasons: List[str] = []

    if np.isfinite(pilot_rel_se) and pilot_rel_se > 0.0:
        required_rel = int(
            math.ceil(
                pilot_reps
                * allocation_safety_factor
                * (pilot_rel_se / target_relative_se) ** 2
            )
        )
        planned = max(planned, required_rel)
        reasons.append(f"relative_se:{required_rel}")
    else:
        planned = max_confirmation_reps
        reasons.append("relative_se:unresolved")

    if pilot_tail_ess > 0.0:
        required_ess = int(
            math.ceil(
                pilot_reps
                * allocation_safety_factor
                * target_tail_ess
                / pilot_tail_ess
            )
        )
        planned = max(planned, required_ess)
        reasons.append(f"tail_ess:{required_ess}")
    else:
        planned = max_confirmation_reps
        reasons.append("tail_ess:unresolved")

    confirmation_reps = min(max_confirmation_reps, planned)
    confirmation = importance_sampling_bootstrap_p(
        counts,
        pi_host,
        pi_trans,
        A0,
        observed_stat,
        observed_lambda,
        confirmation_reps,
        rng,
        eta_values,
        grid_size=grid_size,
    )
    confirmation.update({
        "importance_pilot_reps": int(pilot_reps),
        "importance_pilot_p": pilot.get("p_importance", float("nan")),
        "importance_pilot_mc_se": pilot.get("p_importance_mc_se", float("nan")),
        "importance_pilot_relative_se": pilot_rel_se,
        "importance_pilot_tail_ess": pilot_tail_ess,
        "importance_confirmation_reps": int(confirmation_reps),
        "importance_total_reps_used": int(pilot_reps + confirmation_reps),
        "importance_confirmation_max_reps": int(max_confirmation_reps),
        "importance_allocation_reason": ",".join(reasons),
        "importance_confirmation_reps_saved": int(
            max_confirmation_reps - confirmation_reps
        ),
    })
    return confirmation


def projected_residuals(
    counts: np.ndarray,
    codon_indices: np.ndarray,
    pi_fit: np.ndarray,
    direction: np.ndarray,
) -> Tuple[np.ndarray, np.ndarray]:
    ns = counts.sum(axis=1)
    p_obs = counts / ns[:, None]
    norm_d = float(np.linalg.norm(direction))
    if norm_d <= 1e-12:
        scalar = np.zeros(len(ns), dtype=float)
    else:
        scalar = ((p_obs - pi_fit) @ direction) / norm_d
    return codon_indices.astype(int), scalar.astype(float)


def lag1_for_consecutive_codons(codon_indices: np.ndarray, residuals: np.ndarray) -> Tuple[float, int]:
    if len(codon_indices) < 3:
        return float("nan"), 0
    xs: List[float] = []
    ys: List[float] = []
    for i in range(len(codon_indices) - 1):
        if int(codon_indices[i + 1]) == int(codon_indices[i]) + 1:
            xs.append(float(residuals[i]))
            ys.append(float(residuals[i + 1]))
    if len(xs) < 3:
        return float("nan"), len(xs)
    x = np.asarray(xs, dtype=float)
    y = np.asarray(ys, dtype=float)
    if np.std(x) <= 1e-12 or np.std(y) <= 1e-12:
        return float("nan"), len(xs)
    return float(np.corrcoef(x, y)[0, 1]), len(xs)


def contiguous_residual_blocks(
    codon_indices: np.ndarray,
    residual_vectors: np.ndarray,
    block_size: int,
) -> List[np.ndarray]:
    blocks: List[np.ndarray] = []
    if block_size <= 0:
        return blocks
    for start in range(0, len(codon_indices) - block_size + 1):
        idx = codon_indices[start:start + block_size]
        if np.all(np.diff(idx) == 1):
            blocks.append(residual_vectors[start:start + block_size].copy())
    return blocks


def residual_block_bootstrap_p(
    counts: np.ndarray,
    codon_indices: np.ndarray,
    pi_host: np.ndarray,
    pi_trans: np.ndarray,
    A0: float,
    observed_stat: float,
    reps: int,
    block_size: int,
    rng: np.random.Generator,
    grid_size: int = 101,
) -> Optional[float]:
    """
    Moving-block residual bootstrap sensitivity analysis under H0.

    Residual compositions are centered to impose the host-only null, sampled in
    contiguous blocks, added back to pi_host, projected to the simplex, and then
    converted to integer counts using the original codon totals.

    This is deliberately treated as a sensitivity bootstrap rather than the
    primary inferential engine. The primary bootstrap remains the iid DM
    parametric bootstrap.
    """
    ns = counts.sum(axis=1)
    p_obs = counts / ns[:, None]
    residual = p_obs - pi_host[None, :]
    residual = residual - residual.mean(axis=0, keepdims=True)
    blocks = contiguous_residual_blocks(codon_indices, residual, block_size)
    if len(blocks) < 2:
        return None

    ge = 0
    m = len(counts)
    for _ in range(reps):
        sampled: List[np.ndarray] = []
        while sum(len(x) for x in sampled) < m:
            sampled.append(blocks[int(rng.integers(0, len(blocks)))])
        resampled = np.vstack(sampled)[:m]
        sim = np.zeros_like(counts, dtype=int)
        for i, n in enumerate(ns):
            p = project_to_simplex(pi_host + resampled[i])
            sim[i] = rng.multinomial(int(n), p)
        _, _, _, stat_b, _ = fit_lambda_lrt(sim, pi_host, pi_trans, A0, grid_size=grid_size)
        if stat_b >= observed_stat - 1e-12:
            ge += 1
    return (1.0 + ge) / (reps + 1.0)


