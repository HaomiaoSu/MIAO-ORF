def parse_bool(x: object) -> bool:
    return str(x).strip().lower() in {"1", "true", "t", "yes", "y"}


def parse_binary_flag(x: object, field: str, path: str, torf_id: str) -> bool:
    value = str(x).strip()
    if value not in {"0", "1"}:
        raise SystemExit(
            f"ERROR: {field} must be 0 or 1 in {path}; "
            f"torf_id={torf_id!r}, value={value!r}"
        )
    return value == "1"


