def sha256_file(path: str) -> str:
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def file_identity(path: str, hash_limit_bytes: int = 64 * 1024 * 1024) -> Dict[str, object]:
    """Return stable path/stat metadata and hash reasonably sized files."""
    absolute = os.path.abspath(path)
    identity: Dict[str, object] = {"path": absolute, "exists": os.path.isfile(absolute)}
    if not identity["exists"]:
        return identity
    stat = os.stat(absolute)
    identity.update({
        "size_bytes": int(stat.st_size),
        "mtime_utc": dt.datetime.fromtimestamp(
            stat.st_mtime, tz=dt.timezone.utc
        ).isoformat(),
    })
    if stat.st_size <= hash_limit_bytes:
        identity["sha256"] = sha256_file(absolute)
        identity["sha256_status"] = "computed"
    else:
        identity["sha256"] = None
        identity["sha256_status"] = f"skipped_larger_than_{hash_limit_bytes}_bytes"
    return identity


def json_safe(value: object) -> object:
    if value is None or isinstance(value, (str, int, float, bool)):
        return value
    if isinstance(value, (list, tuple)):
        return [json_safe(item) for item in value]
    if isinstance(value, dict):
        return {str(key): json_safe(item) for key, item in value.items()}
    return str(value)


def write_run_manifest(
    path: str,
    args: argparse.Namespace,
    torf_paths: Sequence[str],
    output_paths: Sequence[str],
    template_info: Dict[str, object],
    result_count: int,
) -> None:
    """Write the complete formal run contract and provenance as atomic JSON."""
    caller_path = os.path.abspath(__file__)
    bam_index_candidates = [f"{args.psite_bam}.bai"]
    if str(args.psite_bam).endswith(".bam"):
        bam_index_candidates.append(str(args.psite_bam)[:-4] + ".bai")
    bam_index = next((item for item in bam_index_candidates if os.path.isfile(item)), None)
    inputs = {
        "psite_bam": file_identity(args.psite_bam),
        "psite_bam_index": file_identity(bam_index) if bam_index else None,
        "torf_files": [file_identity(item) for item in torf_paths],
        "dm_background": file_identity(args.dm_background) if args.dm_background else None,
    }
    manifest = {
        "program": PROGRAM_NAME,
        "version": __version__,
        "output_schema_version": OUTPUT_SCHEMA_VERSION,
        "statistical_engine_id": STATISTICAL_ENGINE_ID,
        "benchmark_certification_id": BENCHMARK_CERTIFICATION_ID,
        "generated_at_utc": dt.datetime.now(dt.timezone.utc).isoformat(),
        "command": [sys.executable, *sys.argv],
        "working_directory": os.getcwd(),
        "runtime": {
            "python": sys.version,
            "platform": platform.platform(),
            "executable": sys.executable,
        },
        "source": {
            "caller": file_identity(caller_path, hash_limit_bytes=2**63 - 1),
        },
        "parameters": {
            key: json_safe(value)
            for key, value in sorted(vars(args).items())
            if not key.endswith("_parsed")
        },
        "inputs": inputs,
        "outputs": [file_identity(item) for item in output_paths],
        "result_rows": int(result_count),
        "background": {
            "source": template_info.get("background_source", "reestimated"),
            "path": template_info.get("background_path", ""),
            "pi_method": args.pi_method,
            "A0": json_safe(template_info.get("A0")),
        },
        "output_schema": result_columns(args.block_sizes_parsed),
        "read_count_semantics": {
            "orf_region_reads": "observed P-sites across the full candidate ORF interval",
            "analyzed_core_reads": "observed P-sites after configured start/stop codon exclusions; identical to legacy core_reads",
            "observed_phase*_core_reads": "observed core P-sites by intORF-relative phase",
            "model_expected_*": "fractional fitted-mixture expectations, not hard read-level assignments",
        },
        "lambda_interval_semantics": {
            "columns": ["lambda_profile_ci95_low", "lambda_profile_ci95_high"],
            "confidence_level": LAMBDA_PROFILE_CI_LEVEL,
            "method": "likelihood-ratio profile interval using chi-square(1) cutoff, bounded to [0,1]",
        },
    }
    temporary = f"{path}.tmp"
    with open(temporary, "w", encoding="utf-8") as handle:
        json.dump(manifest, handle, indent=2, ensure_ascii=False, sort_keys=True)
        handle.write("\n")
    os.replace(temporary, path)


