def _candidate_overlap_type_from_metadata(row: ORFRow) -> Optional[str]:
    if row.cds_first_t is None:
        return None
    rel = (row.t_start - row.cds_first_t) % 3
    if rel == 1:
        return "F1"
    if rel == 2:
        return "F2"
    return None


def _candidate_group_key(row: ORFRow, overlap_type: str, mode: str) -> object:
    blocks_key = (row.chrom, row.strand, tuple(row.blocks), overlap_type)
    if mode == "none":
        return ("torf", row.torf_id)
    if mode == "blocks":
        return ("blocks",) + blocks_key
    gorf_id = str(row.gorf_id or "").strip()
    if gorf_id:
        return ("gorf", gorf_id, overlap_type)
    return ("blocks_fallback",) + blocks_key


def _representative_rank(row: ORFRow) -> Tuple[int, int, str]:
    """Prefer MANE context, then longer peptide, then stable ID."""
    return (1 if row.has_mane else 0, int(row.peptide_len), row.torf_id)


def load_torf_rows(paths: Sequence[str], args: argparse.Namespace) -> Tuple[List[ORFRow], List[ORFRow], Dict[str, int]]:
    template_rows: List[ORFRow] = []
    seen_template: set[str] = set()
    candidate_groups: Dict[object, ORFRow] = {}
    group_member_torfs: Dict[object, List[str]] = defaultdict(list)
    group_member_txs: Dict[object, List[str]] = defaultdict(list)
    confounded_candidate_keys: set[object] = set()
    confounded_same_gene_keys: set[object] = set()
    stats: Counter[str] = Counter()

    required = {
        "torf_id", "gene_id", "gene_name", "transcript_id", "chrom", "strand",
        "t_start", "t_end", "aa_len", "orf_biotype", "is_annotated_cds",
        "has_MANE_Select_tag", "blockSizes", "genomic_block_starts1", "cds_first_t",
        "intorf_shares_annotated_stop_same_gene", "intorf_shares_annotated_stop_any_gene",
        "intorf_annotated_stop_confounded",
    }

    for path in paths:
        with open(path, "r", encoding="utf-8") as handle:
            reader = csv.DictReader(handle, delimiter="\t")
            fields = set(reader.fieldnames or [])
            missing = sorted(required - fields)
            if missing:
                raise SystemExit(f"ERROR: missing columns in {path}: {', '.join(missing)}")
            if args.candidate_dedup == "gorf" and "gorf_id" not in fields:
                stats["files_without_gorf_id_fallback_to_blocks"] += 1

            for raw in reader:
                orf_biotype = raw.get("orf_biotype", "")
                if orf_biotype not in {"CDS", "intORF_altframe"}:
                    stats["skip_irrelevant_orf_rows"] += 1
                    continue

                if orf_biotype == "CDS":
                    is_annotated_cds = parse_bool(raw.get("is_annotated_cds", "0"))
                    has_mane = parse_bool(raw.get("has_MANE_Select_tag", "0"))
                    if not (is_annotated_cds and has_mane):
                        stats["skip_non_template_cds_rows"] += 1
                        continue
                else:
                    is_annotated_cds = False
                    has_mane = parse_bool(raw.get("has_MANE_Select_tag", "0"))

                blocks = parse_blocks_01(raw.get("blockSizes", ""), raw.get("genomic_block_starts1", ""))
                if not blocks:
                    stats["skip_invalid_blocks"] += 1
                    continue

                cds_first_t: Optional[int] = None
                if orf_biotype == "intORF_altframe":
                    cds_first_raw = raw.get("cds_first_t", "")
                    cds_first_t = None if cds_first_raw in ("", None) else safe_int(cds_first_raw, -1)
                    if cds_first_t is not None and cds_first_t < 0:
                        cds_first_t = None
                peptide_len = safe_int(raw.get("peptide_len", raw.get("aa_len", 0)), safe_int(raw.get("aa_len", 0), 0))
                torf_id = raw["torf_id"]
                shared_stop_same_gene = False
                shared_stop_any_gene = False
                annotated_stop_confounded = False
                if orf_biotype == "intORF_altframe":
                    shared_stop_same_gene = parse_binary_flag(
                        raw.get("intorf_shares_annotated_stop_same_gene", ""),
                        "intorf_shares_annotated_stop_same_gene",
                        path,
                        torf_id,
                    )
                    shared_stop_any_gene = parse_binary_flag(
                        raw.get("intorf_shares_annotated_stop_any_gene", ""),
                        "intorf_shares_annotated_stop_any_gene",
                        path,
                        torf_id,
                    )
                    annotated_stop_confounded = parse_binary_flag(
                        raw.get("intorf_annotated_stop_confounded", ""),
                        "intorf_annotated_stop_confounded",
                        path,
                        torf_id,
                    )
                    if shared_stop_same_gene and not shared_stop_any_gene:
                        raise SystemExit(
                            "ERROR: inconsistent annotated-stop flags: same-gene match requires any-gene match; "
                            f"file={path}, torf_id={torf_id!r}"
                        )
                    if annotated_stop_confounded != shared_stop_any_gene:
                        raise SystemExit(
                            "ERROR: inconsistent annotated-stop flags: intorf_annotated_stop_confounded "
                            "must equal intorf_shares_annotated_stop_any_gene; "
                            f"file={path}, torf_id={torf_id!r}"
                        )
                row = ORFRow(
                    raw=raw,
                    torf_id=torf_id,
                    gene_id=raw.get("gene_id", ""),
                    gene_name=raw.get("gene_name", ""),
                    transcript_id=raw.get("transcript_id", ""),
                    chrom=raw["chrom"],
                    strand=raw.get("strand", "+") or "+",
                    blocks=blocks,
                    t_start=safe_int(raw.get("t_start", 0), 0),
                    t_end=safe_int(raw.get("t_end", 0), 0),
                    aa_len=safe_int(raw.get("aa_len", 0), 0),
                    peptide_len=peptide_len,
                    cds_first_t=cds_first_t,
                    orf_biotype=orf_biotype,
                    is_annotated_cds=is_annotated_cds,
                    has_mane=has_mane,
                    intorf_shares_annotated_stop_same_gene=shared_stop_same_gene,
                    intorf_shares_annotated_stop_any_gene=shared_stop_any_gene,
                    intorf_annotated_stop_confounded=annotated_stop_confounded,
                    gorf_id=str(raw.get("gorf_id", "")).strip(),
                    member_torf_ids_preview=raw.get("torf_id", ""),
                    member_transcripts_preview=raw.get("transcript_id", ""),
                )

                if orf_biotype == "intORF_altframe" and not row.gorf_id:
                    stats["candidate_rows_missing_gorf_id"] += 1
                    if args.require_gorf_id and args.candidate_dedup == "gorf":
                        raise SystemExit(
                            "ERROR: --require-gorf-id was requested, but an intORF_altframe row "
                            f"has an empty gorf_id in {path}: torf_id={row.torf_id!r}"
                        )

                if orf_biotype == "CDS":
                    if row.torf_id not in seen_template:
                        template_rows.append(row)
                        seen_template.add(row.torf_id)
                    continue

                stats["raw_intorf_altframe_rows"] += 1
                overlap_type = _candidate_overlap_type_from_metadata(row)
                if overlap_type is None:
                    stats["skip_invalid_overlap_type_metadata"] += 1
                    continue
                key = _candidate_group_key(row, overlap_type, args.candidate_dedup)
                if row.intorf_annotated_stop_confounded:
                    stats["annotated_stop_confounded_raw_rows"] += 1

                if row.peptide_len < args.min_intorf_aa:
                    stats["skip_too_short_metadata"] += 1
                    continue
                n_total_codons = max(0, row.orf_len_nt // 3)
                n_core_codons = max(0, n_total_codons - max(0, int(args.exclude_start_codons)) - max(0, int(args.exclude_stop_codons)))
                if n_core_codons < args.min_core_codons:
                    stats["skip_too_few_core_codons_metadata"] += 1
                    continue
                if args.candidate_mane_only and not row.has_mane:
                    stats["skip_non_mane_candidate"] += 1
                    continue
                if row.intorf_annotated_stop_confounded:
                    confounded_candidate_keys.add(key)
                    stats["annotated_stop_confounded_metadata_eligible_rows"] += 1
                    if row.intorf_shares_annotated_stop_same_gene:
                        confounded_same_gene_keys.add(key)
                group_member_torfs[key].append(row.torf_id)
                if row.transcript_id:
                    group_member_txs[key].append(row.transcript_id)
                if key in candidate_groups:
                    stats["merged_duplicate_torf_rows"] += 1
                    if _representative_rank(row) > _representative_rank(candidate_groups[key]):
                        candidate_groups[key] = row
                else:
                    candidate_groups[key] = row

    preview_n = max(1, int(args.member_preview_n))
    candidate_rows: List[ORFRow] = []
    for key, row in candidate_groups.items():
        group_is_confounded = key in confounded_candidate_keys
        if group_is_confounded:
            stats["annotated_stop_confounded_candidate_contexts"] += 1
            row.intorf_annotated_stop_confounded = True
            row.intorf_shares_annotated_stop_any_gene = True
            if key in confounded_same_gene_keys:
                row.intorf_shares_annotated_stop_same_gene = True
        if group_is_confounded and not args.include_annotated_stop_confounded:
            stats["skip_annotated_stop_confounded_gorf_contexts"] += 1
            if key in confounded_same_gene_keys:
                stats["skip_shared_annotated_stop_same_gene_gorf_contexts"] += 1
            else:
                stats["skip_shared_annotated_stop_other_gene_gorf_contexts"] += 1
            continue
        torfs = sorted(set(group_member_torfs.get(key, [])))
        txs = sorted(set(group_member_txs.get(key, [])))
        row.n_member_torfs = len(torfs)
        row.n_member_transcripts = len(txs)
        row.member_torf_ids_preview = ",".join(torfs[:preview_n])
        row.member_transcripts_preview = ",".join(txs[:preview_n])
        candidate_rows.append(row)
    stats["kept_gorf_context_candidates"] = len(candidate_rows)
    return template_rows, candidate_rows, dict(stats)


