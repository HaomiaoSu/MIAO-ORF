class TemplateAccumulator:
    def __init__(self, reservoir_size: int, seed: int):
        self.patterns: Counter[Tuple[int, int, int]] = Counter()
        self.sum_counts = np.zeros(3, dtype=float)
        self.sum_props = np.zeros(3, dtype=float)
        self.n_codons = 0
        self.n_cds_seen = 0
        self.n_cds_kept = 0
        self.reservoir_size = max(0, int(reservoir_size))
        self.reservoir: List[Tuple[float, float, float]] = []
        self.rng = np.random.default_rng(seed)

    def add_codon(self, c: Sequence[int]) -> None:
        arr = np.asarray(c, dtype=int)
        n = int(arr.sum())
        if n <= 0:
            return
        tup = (int(arr[0]), int(arr[1]), int(arr[2]))
        self.patterns[tup] += 1
        self.sum_counts += arr
        self.sum_props += arr / float(n)
        self.n_codons += 1

        if self.reservoir_size <= 0:
            return
        p = (float(arr[0] / n), float(arr[1] / n), float(arr[2] / n))
        if len(self.reservoir) < self.reservoir_size:
            self.reservoir.append(p)
        else:
            idx = int(self.rng.integers(0, self.n_codons))
            if idx < self.reservoir_size:
                self.reservoir[idx] = p


def trimmed_component_mean(reservoir: Sequence[Tuple[float, float, float]], trim_fraction: float) -> np.ndarray:
    if not reservoir:
        return np.array([1 / 3, 1 / 3, 1 / 3], dtype=float)
    x = np.asarray(reservoir, dtype=float)
    trim_fraction = min(max(float(trim_fraction), 0.0), 0.49)
    out: List[float] = []
    for f in range(3):
        vals = np.sort(x[:, f])
        k = int(math.floor(trim_fraction * len(vals)))
        use = vals[k: len(vals) - k] if len(vals) - 2 * k > 0 else vals
        out.append(float(np.mean(use)))
    p = np.asarray(out, dtype=float)
    return p / p.sum()


def dm_logpmf_pattern(c: np.ndarray, alpha: np.ndarray) -> float:
    n = int(c.sum())
    A = float(alpha.sum())
    return float(
        gammaln(n + 1)
        - np.sum(gammaln(c + 1))
        + gammaln(A)
        - gammaln(n + A)
        + np.sum(gammaln(c + alpha) - gammaln(alpha))
    )


def estimate_A0_mle(patterns: Counter[Tuple[int, int, int]], pi: np.ndarray) -> float:
    if not patterns:
        return 20.0
    pi = np.clip(np.asarray(pi, dtype=float), 1e-9, 1.0)
    pi = pi / pi.sum()

    unique = [(np.asarray(k, dtype=float), int(freq)) for k, freq in patterns.items()]

    def objective(log_A: float) -> float:
        A = float(np.exp(log_A))
        alpha = A * pi
        ll = 0.0
        for c, freq in unique:
            ll += freq * dm_logpmf_pattern(c, alpha)
        return -ll

    fit = minimize_scalar(
        objective,
        bounds=(math.log(0.02), math.log(1e5)),
        method="bounded",
        options={"xatol": 1e-5, "maxiter": 300},
    )
    if not fit.success:
        sys.stderr.write(f"WARN: A0 optimization did not fully converge: {fit.message}\n")
    return float(np.exp(fit.x))


def estimate_template(
    bam: pysam.AlignmentFile,
    rows: Sequence[ORFRow],
    args: argparse.Namespace,
) -> Tuple[np.ndarray, float, Dict[str, object]]:
    acc = TemplateAccumulator(args.trim_reservoir_size, args.seed)

    for row in rows:
        acc.n_cds_seen += 1
        if row.orf_len_nt < args.template_min_cds_nt:
            continue
        tcounts = count_psites_by_tindex(bam, row, args.rl, args.rl_source)
        total_reads = sum(tcounts.values())
        density = total_reads / float(max(row.orf_len_nt, 1))
        if density < args.template_min_density:
            continue

        mat = codon_count_matrix(tcounts, row.orf_len_nt)
        start_codon_idx = int(math.ceil(args.template_trim_start_nt / 3.0))
        end_codon_idx = int(math.floor((row.orf_len_nt - args.template_trim_stop_nt) / 3.0))
        if end_codon_idx <= start_codon_idx:
            continue

        kept_any = False
        for c in mat[start_codon_idx:end_codon_idx]:
            if int(c.sum()) < args.template_min_codon_reads:
                continue
            acc.add_codon(c)
            kept_any = True
        if kept_any:
            acc.n_cds_kept += 1

    if acc.n_codons == 0:
        raise SystemExit("ERROR: no template codons survived filters; loosen template filters or check BAM / TSV compatibility")

    pi_read = acc.sum_counts / acc.sum_counts.sum()
    pi_equal = acc.sum_props / float(acc.n_codons)
    pi_equal = pi_equal / pi_equal.sum()
    pi_trim = trimmed_component_mean(acc.reservoir, args.trim_fraction)

    if args.pi_method == "read_weighted":
        pi_used = pi_read
    elif args.pi_method == "trimmed":
        pi_used = pi_trim
    else:
        pi_used = pi_equal

    A0 = estimate_A0_mle(acc.patterns, pi_used)
    extra: Dict[str, object] = {
        "pi_read_weighted": pi_read,
        "pi_codon_equal": pi_equal,
        "pi_trimmed": pi_trim,
        "pi_used": pi_used,
        "A0": A0,
        "alpha0": A0 * pi_used,
        "template_cds_seen": acc.n_cds_seen,
        "template_cds_kept": acc.n_cds_kept,
        "template_codons": acc.n_codons,
        "template_patterns": len(acc.patterns),
        "trim_reservoir_n": len(acc.reservoir),
        "template_status": "success",
        "background_source": "reestimated",
        "background_path": "",
        "background_pi_method": args.pi_method,
    }
    return pi_used, A0, extra


def summarize_candidate_reads(
    mat_all: np.ndarray,
    mat_core: np.ndarray,
    active_mask: np.ndarray,
) -> Dict[str, object]:
    """Summarize observed P-sites without implying read-level source assignment."""
    core_phase_reads = (
        np.asarray(mat_core, dtype=int).sum(axis=0)
        if len(mat_core)
        else np.zeros(3, dtype=int)
    )
    core_reads = int(core_phase_reads.sum())
    metrics: Dict[str, object] = {
        "n_total_orf_codons_including_stop": int(len(mat_all)),
        "n_core_codons": int(len(mat_core)),
        "n_active_core_codons": int(np.asarray(active_mask, dtype=bool).sum()),
        "orf_region_reads": int(np.asarray(mat_all, dtype=int).sum()),
        # ``core_reads`` is retained for backward compatibility.  The explicit
        # alias makes clear that this is the effective count used for fitting.
        "core_reads": core_reads,
        "analyzed_core_reads": core_reads,
    }
    for phase in range(3):
        phase_reads = int(core_phase_reads[phase])
        metrics[f"observed_phase{phase}_core_reads"] = phase_reads
        metrics[f"observed_phase{phase}_core_fraction"] = (
            float(phase_reads) / float(core_reads) if core_reads else 0.0
        )
    return metrics


def prepare_core_counts(row: ORFRow, args: argparse.Namespace) -> Tuple[np.ndarray, np.ndarray, Dict[str, object]]:
    """Extract core-codon counts once so low-coverage contexts can skip DM fitting."""
    tcounts = count_psites_by_tindex(None, row, args.rl, args.rl_source)
    mat_all = codon_count_matrix(tcounts, row.orf_len_nt)
    n_total_codons = len(mat_all)
    core_start = max(0, int(args.exclude_start_codons))
    core_end = max(core_start, n_total_codons - max(0, int(args.exclude_stop_codons)))
    mat_core = mat_all[core_start:core_end]
    core_indices = np.arange(core_start, core_end, dtype=int)
    ns_core = mat_core.sum(axis=1) if len(mat_core) else np.array([], dtype=int)
    active_mask = ns_core > 0
    counts = mat_core[active_mask]
    active_indices = core_indices[active_mask]
    metrics = summarize_candidate_reads(mat_all, mat_core, active_mask)
    return counts, active_indices, metrics


def active_core_breadth_metrics(
    n_active_core_codons: int,
    n_core_codons: int,
    args: argparse.Namespace,
) -> Dict[str, object]:
    """Describe final credible-call breadth without changing inference eligibility."""
    active_frac = (
        float(n_active_core_codons) / float(n_core_codons)
        if n_core_codons > 0
        else 0.0
    )
    codons_ok = n_active_core_codons >= args.min_credible_active_core_codons
    frac_ok = active_frac >= args.min_credible_active_core_frac
    if codons_ok and frac_ok:
        label = "pass"
    elif not codons_ok and not frac_ok:
        label = "low_active_core_codons_and_fraction"
    elif not codons_ok:
        label = "low_active_core_codons"
    else:
        label = "low_active_core_fraction"
    return {
        "active_core_codon_frac": active_frac,
        "credible_active_core_codons_ok": int(codons_ok),
        "credible_active_core_frac_ok": int(frac_ok),
        "credible_active_core_breadth_ok": int(codons_ok and frac_ok),
        "active_core_breadth_label": label,
    }


def dm_contrast_variance(n: int, pi_target: float, pi_unused: float, A0: float) -> float:
    """Variance of X_target-X_unused under the host-only DM template."""
    if n <= 0 or A0 <= 0:
        return float("nan")
    inflation = n * (n + A0) / (1.0 + A0)
    component = (
        pi_target * (1.0 - pi_target)
        + pi_unused * (1.0 - pi_unused)
        + 2.0 * pi_target * pi_unused
    )
    return max(0.0, inflation * component)


def target_residual_breadth_metrics(
    active_counts: np.ndarray,
    pi_host: np.ndarray,
    A0: float,
    overlap_type: str,
    args: argparse.Namespace,
) -> Dict[str, object]:
    """Count active codons with target-specific residual support.

    Phase 0 is the candidate intORF frame.  The unused phase is the third
    phase that is neither the intORF frame nor the annotated-CDS-dominant
    phase: phase 1 for F1 candidates and phase 2 for F2 candidates.
    """
    unused_index = 1 if overlap_type == "F1" else 2
    active_n = int(len(active_counts))
    supported_codons = 0

    for codon_counts in active_counts:
        n = int(codon_counts.sum())
        target_count = float(codon_counts[0])
        unused_count = float(codon_counts[unused_index])
        target_residual = target_count - n * float(pi_host[0])
        unused_residual = unused_count - n * float(pi_host[unused_index])
        contrast = target_residual - unused_residual
        variance = dm_contrast_variance(
            n,
            float(pi_host[0]),
            float(pi_host[unused_index]),
            A0,
        )
        z = contrast / math.sqrt(variance) if variance > 0 else 0.0
        supported_codons += int(z >= TARGET_VS_UNUSED_Z05_MIN)

    supported_frac = supported_codons / active_n if active_n else 0.0
    breadth_ok = bool(
        active_n > 0
        and supported_frac > args.min_credible_target_residual_frac
    )
    return {
        "residual_evaluable_active_core_codons": active_n,
        "target_vs_unused_z05_codons": supported_codons,
        "target_vs_unused_z05_frac_active": supported_frac,
        "credible_target_residual_breadth_ok": int(breadth_ok),
        "target_residual_breadth_label": "pass" if breadth_ok else "low_target_frame_residual_breadth",
    }


def coverage_prefilter_candidates(
    rows: Sequence[ORFRow],
    args: argparse.Namespace,
    pi_trans: np.ndarray,
    A0: float,
) -> Tuple[List[ORFRow], List[Dict[str, object]], Dict[str, int]]:
    if _ACTIVE_PSITE_INDEX is None:
        raise RuntimeError("Coverage prefilter requires the sparse P-site index")
    kept: List[ORFRow] = []
    rejected: List[Dict[str, object]] = []
    stats: Counter[str] = Counter()
    total = len(rows)
    for idx, row in enumerate(rows, start=1):
        row.candidate_order = idx - 1
        if idx == 1 or idx % 5000 == 0 or idx == total:
            sys.stderr.write(f"[prefilter] {idx:,}/{total:,}\n")
        counts, active_indices, metrics = prepare_core_counts(row, args)
        reason = ""
        if metrics["n_core_codons"] < args.min_core_codons:
            stats["skip_too_few_core_codons"] += 1
            reason = "too_few_core_codons"
        elif metrics["n_active_core_codons"] < args.min_active_core_codons:
            stats["skip_low_active_core_codons"] += 1
            reason = "low_active_core_codons"
        elif metrics["core_reads"] < args.min_core_reads:
            stats["skip_low_core_reads"] += 1
            reason = "low_core_reads"
        if reason:
            out = base_result(row)
            overlap_type = candidate_overlap_type(row)
            out["overlap_type"] = overlap_type or ""
            out.update(metrics)
            out.update(active_core_breadth_metrics(
                metrics["n_active_core_codons"],
                metrics["n_core_codons"],
                args,
            ))
            out["prefilter_reason"] = reason
            out["classification_pre_fdr"] = "insufficient_data"
            out["p_final"] = 1.0
            out["bootstrap_gate_pass"] = 0
            out["bootstrap_method"] = "not_run"
            out["_candidate_order"] = row.candidate_order
            if overlap_type is not None:
                pi_host = pi_host_for_type(pi_trans, overlap_type)
                out.update(target_residual_breadth_metrics(
                    counts,
                    pi_host,
                    A0,
                    overlap_type,
                    args,
                ))
                dom = 2 if overlap_type == "F1" else 1
                out.update({
                    "pi_trans_0": float(pi_trans[0]),
                    "pi_trans_1": float(pi_trans[1]),
                    "pi_trans_2": float(pi_trans[2]),
                    "pi_host_0": float(pi_host[0]),
                    "pi_host_1": float(pi_host[1]),
                    "pi_host_2": float(pi_host[2]),
                    "A0": float(A0),
                    "host_dominant_index": dom,
                    "template_separation_ok": int(
                        abs(float(pi_trans[0] - pi_host[0])) >= args.template_separation_min
                        and abs(float(pi_host[dom] - pi_trans[dom])) >= args.template_separation_min
                    ),
                })
            rejected.append(out)
            continue
        row.prepared_mat_core = counts
        row.prepared_core_indices = active_indices
        row.prepared_read_metrics = metrics
        kept.append(row)
    stats["coverage_prefilter_input"] = total
    stats["coverage_prefilter_kept"] = len(kept)
    stats["coverage_prefilter_rejected_written"] = len(rejected)
    return kept, rejected, dict(stats)


