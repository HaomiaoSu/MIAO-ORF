def geometry_metrics(pi_obs: np.ndarray, pi_host: np.ndarray, pi_trans: np.ndarray, overlap_type: str, args: argparse.Namespace) -> Dict[str, object]:
    dom = 2 if overlap_type == "F1" else 1
    gain_denom = float(pi_trans[0] - pi_host[0])
    drop_denom = float(pi_host[dom] - pi_trans[dom])
    denom_ok = abs(gain_denom) >= args.template_separation_min and abs(drop_denom) >= args.template_separation_min

    lambda_gain_raw = float("nan") if abs(gain_denom) < 1e-12 else float((pi_obs[0] - pi_host[0]) / gain_denom)
    lambda_drop_raw = float("nan") if abs(drop_denom) < 1e-12 else float((pi_host[dom] - pi_obs[dom]) / drop_denom)

    d = pi_trans - pi_host
    delta = pi_obs - pi_host
    d2 = float(d @ d)
    lambda_proj_raw = float("nan") if d2 <= 1e-15 else float((delta @ d) / d2)
    lambda_proj_clipped = float("nan") if not np.isfinite(lambda_proj_raw) else float(np.clip(lambda_proj_raw, 0.0, 1.0))
    residual_segment = delta - lambda_proj_clipped * d if np.isfinite(lambda_proj_clipped) else np.full(3, np.nan)
    distance_segment = float(np.linalg.norm(residual_segment)) if np.all(np.isfinite(residual_segment)) else float("nan")

    abs_diff = float(abs(lambda_gain_raw - lambda_drop_raw)) if np.isfinite(lambda_gain_raw) and np.isfinite(lambda_drop_raw) else float("nan")
    rel_diff = (
        float(abs_diff / (max(abs(lambda_gain_raw), abs(lambda_drop_raw)) + args.lambda_rel_eps))
        if np.isfinite(abs_diff)
        else float("nan")
    )
    consistent = bool(
        denom_ok
        and np.isfinite(abs_diff)
        and np.isfinite(rel_diff)
        and abs_diff < args.lambda_abs_diff_max
        and rel_diff < args.lambda_rel_diff_max
    )

    return {
        "host_dominant_index": dom,
        "alt_frame_gain": float(pi_obs[0] - pi_host[0]),
        "host_frame_drop": float(pi_obs[dom] - pi_host[dom]),
        "lambda_gain_raw": lambda_gain_raw,
        "lambda_drop_raw": lambda_drop_raw,
        "lambda_gain_clipped": float(np.clip(lambda_gain_raw, 0.0, 1.0)) if np.isfinite(lambda_gain_raw) else float("nan"),
        "lambda_drop_clipped": float(np.clip(lambda_drop_raw, 0.0, 1.0)) if np.isfinite(lambda_drop_raw) else float("nan"),
        "lambda_abs_diff": abs_diff,
        "lambda_rel_diff": rel_diff,
        "mixture_geometry_consistent": int(consistent),
        "lambda_proj_raw": lambda_proj_raw,
        "lambda_proj_clipped": lambda_proj_clipped,
        "distance_to_mixture_segment": distance_segment,
    }


