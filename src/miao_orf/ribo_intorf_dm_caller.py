# Sparse index: (chrom, strand) -> (sorted genomic positions, counts).
# It is built once. Fork-based Linux/WSL workers inherit the index; spawn-based
# workers remain correct because prepared core matrices are serialized after the
# default coverage prefilter, or they fall back to independent BAM handles.
_ACTIVE_PSITE_INDEX: Optional[Dict[Tuple[str, str], Tuple[np.ndarray, np.ndarray]]] = None

def build_sparse_psite_index(
    bam_path: str,
    rl: Optional[int],
    rl_source: str,
) -> Dict[Tuple[str, str], Tuple[np.ndarray, np.ndarray]]:
    counters: Dict[Tuple[str, str], Counter[int]] = defaultdict(Counter)
    total = 0
    kept = 0
    with pysam.AlignmentFile(bam_path, "rb") as bam:
        for read in bam.fetch(until_eof=True):
            total += 1
            if read.is_unmapped:
                continue
            if not read_has_rl(read, rl, rl_source):
                continue
            chrom = bam.get_reference_name(read.reference_id)
            if chrom is None:
                continue
            strand = bam_strand(read)
            p = int(read.reference_start)
            counters[(chrom, strand)][p] += 1
            kept += 1
    out: Dict[Tuple[str, str], Tuple[np.ndarray, np.ndarray]] = {}
    unique_sites = 0
    for key, counter in counters.items():
        items = sorted(counter.items())
        pos = np.fromiter((x[0] for x in items), dtype=np.int64, count=len(items))
        cnt = np.fromiter((x[1] for x in items), dtype=np.int64, count=len(items))
        out[key] = (pos, cnt)
        unique_sites += len(items)
    sys.stderr.write(
        f"[index] scanned alignments={total:,}, kept={kept:,}, unique P-site positions={unique_sites:,}\n"
    )
    return out

def _block_offsets(row: ORFRow) -> Dict[Tuple[int, int], int]:
    blocks_tx = row.blocks if row.strand == "+" else list(reversed(row.blocks))
    out: Dict[Tuple[int, int], int] = {}
    t = 0
    for gs, ge in blocks_tx:
        out[(gs, ge)] = t
        t += ge - gs
    return out

def count_psites_from_index(row: ORFRow) -> Dict[int, int]:
    if _ACTIVE_PSITE_INDEX is None:
        return {}
    arrs = _ACTIVE_PSITE_INDEX.get((row.chrom, row.strand))
    if arrs is None:
        return {}
    pos, vals = arrs
    offsets = _block_offsets(row)
    out: Dict[int, int] = {}
    for gs, ge in row.blocks:
        lo = int(np.searchsorted(pos, gs, side="left"))
        hi = int(np.searchsorted(pos, ge, side="left"))
        if hi <= lo:
            continue
        offset = offsets[(gs, ge)]
        for p, count in zip(pos[lo:hi], vals[lo:hi]):
            ti = offset + (int(p) - gs if row.strand == "+" else (ge - 1 - int(p)))
            out[ti] = out.get(ti, 0) + int(count)
    return out

def tindex_of_gpos(row: ORFRow, gpos: int) -> Optional[int]:
    t = 0
    blocks = row.blocks if row.strand == "+" else list(reversed(row.blocks))
    for gs, ge in blocks:
        if gs <= gpos < ge:
            return t + ((gpos - gs) if row.strand == "+" else ((ge - 1) - gpos))
        t += ge - gs
    return None


def count_psites_by_tindex(
    bam: Optional[pysam.AlignmentFile],
    row: ORFRow,
    rl: Optional[int],
    rl_source: str = "auto",
) -> Dict[int, int]:
    if _ACTIVE_PSITE_INDEX is not None:
        return count_psites_from_index(row)
    if bam is None:
        raise RuntimeError("BAM handle is required when sparse P-site index is disabled")
    counts: Dict[int, int] = {}
    for gs, ge in row.blocks:
        if ge <= gs:
            continue
        for read in bam.fetch(row.chrom, gs, ge):
            if read.is_unmapped:
                continue
            if bam_strand(read) != row.strand:
                continue
            if not read_has_rl(read, rl, rl_source):
                continue
            p = int(read.reference_start)
            if not (gs <= p < ge):
                continue
            ti = tindex_of_gpos(row, p)
            if ti is None:
                continue
            counts[ti] = counts.get(ti, 0) + 1
    return counts


def codon_count_matrix(
    tindex_counts: Dict[int, int],
    orf_len_nt: int,
) -> np.ndarray:
    n_codons = max(0, orf_len_nt // 3)
    mat = np.zeros((n_codons, 3), dtype=int)
    for ti, count in tindex_counts.items():
        if ti < 0 or ti >= n_codons * 3:
            continue
        mat[ti // 3, ti % 3] += int(count)
    return mat


