def normalize_importance_configuration(args: argparse.Namespace) -> argparse.Namespace:
    """Map the formal and legacy CLI names to one internal execution policy."""
    requested_engine = str(args.bootstrap_engine)
    requested_mode = str(args.importance_mode)
    args.bootstrap_engine_requested = requested_engine
    args.importance_mode_requested = requested_mode
    args.formal_importance_engine = int(requested_engine == "adaptive_importance")

    if requested_engine == "adaptive_importance":
        args.importance_execution_policy = "adaptive"
        args.importance_mode_used = requested_mode
        # Selecting the formal engine is an explicit request for its calibrated
        # continuous-tail p-value, not merely for diagnostic columns.
        args.importance_use_for_p_final = True
    elif requested_engine == "adaptive_importance_trial":
        args.importance_execution_policy = "adaptive"
        args.importance_mode_used = "accurate"
    elif requested_engine == "adaptive_two_stage_importance_trial":
        args.importance_execution_policy = "adaptive"
        args.importance_mode_used = "fast"
    elif requested_engine == "iid_plus_importance_trial":
        args.importance_execution_policy = "always"
        args.importance_mode_used = "accurate"
    else:
        args.importance_execution_policy = "none"
        args.importance_mode_used = "not_run"

    return args


