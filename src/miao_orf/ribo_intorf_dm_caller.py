def parse_fraction(value: str) -> float:
    """Parse a decimal or a simple fraction such as 1/3 for CLI thresholds."""
    text = str(value).strip()
    try:
        if "/" in text:
            fields = text.split("/")
            if len(fields) != 2:
                raise ValueError("expected one slash")
            numerator = float(fields[0])
            denominator = float(fields[1])
            if denominator == 0:
                raise ValueError("denominator is zero")
            result = numerator / denominator
        else:
            result = float(text)
    except ValueError as exc:
        raise argparse.ArgumentTypeError(
            f"expected a decimal or simple fraction, got {value!r}"
        ) from exc
    if not math.isfinite(result):
        raise argparse.ArgumentTypeError(f"threshold must be finite, got {value!r}")
    return result


