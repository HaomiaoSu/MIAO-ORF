def main() -> None:
    args = normalize_importance_configuration(parse_args())
    require_dependencies()

    if args.primary_min_intorf_aa is None:
        args.primary_min_intorf_aa = args.min_intorf_aa

    if args.require_gorf_id and args.candidate_dedup != "gorf":
        raise SystemExit("ERROR: --require-gorf-id requires --candidate-dedup gorf")
    if args.min_intorf_aa < 1:
        raise SystemExit("ERROR: --min-intorf-aa must be >= 1")
    if args.primary_min_intorf_aa < args.min_intorf_aa:
        raise SystemExit("ERROR: --primary-min-intorf-aa must be >= --min-intorf-aa")
    if args.seed < 0:
        raise SystemExit("ERROR: --seed must be >= 0")
    if args.bootstrap_reps < 1:
        raise SystemExit("ERROR: --bootstrap-reps must be >= 1")
    if args.importance_reps < 1:
        raise SystemExit("ERROR: --importance-reps must be >= 1")
    if args.importance_pilot_reps < 2:
        raise SystemExit("ERROR: --importance-pilot-reps must be >= 2")
    if args.importance_confirm_min_reps < 2:
        raise SystemExit("ERROR: --importance-confirm-min-reps must be >= 2")
    if args.importance_confirm_min_reps > args.importance_reps:
        raise SystemExit(
            "ERROR: --importance-confirm-min-reps must be <= --importance-reps"
        )
    if args.importance_allocation_safety_factor < 1.0:
        raise SystemExit(
            "ERROR: --importance-allocation-safety-factor must be >= 1"
        )
    if args.importance_min_tail_ess <= 0.0:
        raise SystemExit("ERROR: --importance-min-tail-ess must be > 0")
    if args.importance_max_relative_se <= 0.0:
        raise SystemExit("ERROR: --importance-max-relative-se must be > 0")
    if args.importance_iid_exceedance_threshold < 1:
        raise SystemExit("ERROR: --importance-iid-exceedance-threshold must be >= 1")
    if args.importance_use_for_p_final and args.bootstrap_engine not in {
        "adaptive_importance",
        "iid_plus_importance_trial",
        "adaptive_importance_trial",
        "adaptive_two_stage_importance_trial",
    }:
        raise SystemExit(
            "ERROR: --importance-use-for-p-final requires an importance bootstrap engine"
        )
    if args.bootstrap_engine == "adaptive_importance":
        sys.stderr.write(
            "[init] formal adaptive importance: "
            f"mode={args.importance_mode_used}, max_reps={args.importance_reps}, "
            f"iid_exceedance_threshold={args.importance_iid_exceedance_threshold}\n"
        )
    elif args.bootstrap_engine.endswith("_trial"):
        sys.stderr.write(
            "WARNING: legacy trial bootstrap engine requested; prefer "
            "--bootstrap-engine adaptive_importance --importance-mode "
            f"{args.importance_mode_used}\n"
        )
    if args.workers < 1:
        raise SystemExit("ERROR: --workers must be >= 1")
    if args.min_a0 <= 0:
        raise SystemExit("ERROR: --min-a0 must be > 0")
    if args.min_credible_active_core_codons < 1:
        raise SystemExit("ERROR: --min-credible-active-core-codons must be >= 1")
    if not 0.0 <= args.min_credible_active_core_frac <= 1.0:
        raise SystemExit("ERROR: --min-credible-active-core-frac must be in [0, 1]")
    if not 0.0 <= args.min_credible_target_residual_frac < 1.0:
        raise SystemExit("ERROR: --min-credible-target-residual-frac must be in [0, 1)")

    out_dir = os.path.dirname(os.path.abspath(args.out_prefix))
    if out_dir:
        os.makedirs(out_dir, exist_ok=True)
    template_path = f"{args.out_prefix}.template.tsv"
    result_path = f"{args.out_prefix}.intorf_dm_results.tsv"
    summary_path = f"{args.out_prefix}.summary.tsv"
    prefilter_path = f"{args.out_prefix}.prefilter_summary.tsv"
    run_manifest_path = f"{args.out_prefix}.run_manifest.json"
    for path in (template_path, result_path, summary_path, prefilter_path, run_manifest_path):
        if os.path.exists(path):
            os.remove(path)
            sys.stderr.write(f"[init] removed stale output: {path}\n")

    try:
        args.block_sizes_parsed = sorted({int(x) for x in str(args.block_sizes).split(",") if int(x) >= 2})
    except Exception as exc:
        raise SystemExit(f"ERROR: invalid --block-sizes {args.block_sizes!r}: {exc}")
    try:
        args.importance_etas_parsed = sorted(
            {float(x) for x in str(args.importance_etas).split(",") if str(x).strip()}
        )
    except Exception as exc:
        raise SystemExit(f"ERROR: invalid --importance-etas {args.importance_etas!r}: {exc}")
    if not args.importance_etas_parsed or any(
        not math.isfinite(value) or value < 0.0 or value > 1.0
        for value in args.importance_etas_parsed
    ):
        raise SystemExit("ERROR: --importance-etas must contain finite values in [0, 1]")

    validate_rl_filter_source(args.psite_bam, args.rl, args.rl_source)

    torf_paths = list_input_torfs(args.torf)
    sys.stderr.write(f"[init] tORF files: {len(torf_paths)}\n")
    template_rows, candidate_rows, candidate_load_stats = load_torf_rows(torf_paths, args)
    for candidate_order, row in enumerate(candidate_rows):
        row.candidate_order = candidate_order
    sys.stderr.write(f"[init] MANE CDS templates: {len(template_rows):,}\n")
    sys.stderr.write(
        "[init] intORF_altframe rows: raw=%s, after metadata filters and gORF-context merge=%s\n"
        % (
            f"{candidate_load_stats.get('raw_intorf_altframe_rows', 0):,}",
            f"{len(candidate_rows):,}",
        )
    )
    for key in sorted(candidate_load_stats):
        if key not in {"raw_intorf_altframe_rows", "kept_candidate_rows"}:
            sys.stderr.write(f"[init]   {key}: {candidate_load_stats[key]:,}\n")

    if not template_rows and not args.dm_background:
        write_prefilter_summary(prefilter_path, candidate_load_stats, {}, args)
        sys.stderr.write(f"[ok] wrote {prefilter_path}\n")
        raise SystemExit("ERROR: no MANE annotated CDS rows found in input TSV files")
    if not candidate_rows:
        write_prefilter_summary(prefilter_path, candidate_load_stats, {}, args)
        sys.stderr.write(f"[ok] wrote {prefilter_path}\n")
        raise SystemExit(
            "ERROR: no intORF_altframe candidates survived metadata, annotated-stop, and grouping filters"
        )

    coverage_prefilter_stats: Dict[str, int] = {}
    prefilter_rejected_results: List[Dict[str, object]] = []
    bam = pysam.AlignmentFile(args.psite_bam, "rb")
    try:
        if args.dm_background:
            sys.stderr.write(f"[template] loading validated DM background: {args.dm_background}\n")
            pi_trans, A0, template_info = load_dm_background(args.dm_background, args)
        else:
            sys.stderr.write("[template] estimating pi_trans and A0 from MANE CDS core codons...\n")
            pi_trans, A0, template_info = estimate_template(bam, template_rows, args)
            if A0 < args.min_a0:
                template_info["template_status"] = "failed_low_a0"
                write_template(template_path, template_info, args)
                write_prefilter_summary(prefilter_path, candidate_load_stats, {}, args)
                raise SystemExit(
                    f"ERROR: estimated A0={A0:.10g} is below --min-a0={args.min_a0:.10g}; "
                    "intORF inference is disabled"
                )
        sys.stderr.write(
            "[template] source=%s, pi_trans=(%.6f, %.6f, %.6f), A0=%.6f, codons=%s\n"
            % (template_info["background_source"], pi_trans[0], pi_trans[1], pi_trans[2], A0,
               f"{template_info['template_codons']:,}")
        )

        global _ACTIVE_PSITE_INDEX
        if not args.no_preload_psites:
            sys.stderr.write("[index] building sparse in-memory P-site index for fast candidate counting...\n")
            _ACTIVE_PSITE_INDEX = build_sparse_psite_index(args.psite_bam, args.rl, args.rl_source)
            if not args.no_coverage_prefilter:
                sys.stderr.write("[prefilter] applying core P-site coverage filters before DM fitting...\n")
                candidate_rows, prefilter_rejected_results, coverage_prefilter_stats = coverage_prefilter_candidates(
                    candidate_rows, args, pi_trans, A0
                )
                sys.stderr.write(
                    "[prefilter] kept %s/%s gORF-context candidates after coverage filters\n"
                    % (f"{len(candidate_rows):,}", f"{coverage_prefilter_stats.get('coverage_prefilter_input', 0):,}")
                )
                for key in sorted(coverage_prefilter_stats):
                    if key not in {"coverage_prefilter_input", "coverage_prefilter_kept"}:
                        sys.stderr.write(f"[prefilter]   {key}: {coverage_prefilter_stats[key]:,}\n")
        else:
            sys.stderr.write("[index] disabled; candidate stage will use repeated bam.fetch calls\n")
            if not args.no_coverage_prefilter:
                sys.stderr.write("[prefilter] skipped because sparse P-site index is disabled\n")

        if not candidate_rows and not prefilter_rejected_results:
            write_prefilter_summary(prefilter_path, candidate_load_stats, coverage_prefilter_stats, args)
            sys.stderr.write(f"[ok] wrote {prefilter_path}\n")
            raise SystemExit("ERROR: no gORF-context candidates survived metadata / coverage filters")
        if not candidate_rows and prefilter_rejected_results:
            sys.stderr.write(
                "[prefilter] no candidates survived for DM fitting; all low-coverage candidates "
                "will still be written as insufficient_data\n"
            )

        child_seeds = [stable_candidate_seed(row, args) for row in candidate_rows]
        payloads = list(zip(candidate_rows, child_seeds))
        results: List[Dict[str, object]] = list(prefilter_rejected_results)

        if not candidate_rows:
            pass
        elif args.workers <= 1:
            for idx, (row, seed) in enumerate(payloads, start=1):
                if idx == 1 or idx % 250 == 0 or idx == len(candidate_rows):
                    sys.stderr.write(f"[candidate] {idx:,}/{len(candidate_rows):,}\n")
                rng = np.random.default_rng(seed)
                results.append(analyze_candidate(bam, row, pi_trans, A0, args, rng))
        else:
            # The parent BAM is used only for template estimation. Candidate
            # workers open their own independent BAM handles.
            bam.close()
            bam = None
            sys.stderr.write(f"[candidate] launching {args.workers} workers...\n")
            with mp.Pool(
                processes=args.workers,
                initializer=init_candidate_worker,
                initargs=(args.psite_bam, pi_trans, A0, args),
            ) as pool:
                for idx, result in enumerate(
                    pool.imap(candidate_worker, payloads, chunksize=max(1, args.mp_chunksize)),
                    start=1,
                ):
                    if idx == 1 or idx % 250 == 0 or idx == len(candidate_rows):
                        sys.stderr.write(f"[candidate] {idx:,}/{len(candidate_rows):,}\n")
                    results.append(result)
    finally:
        if bam is not None:
            bam.close()

    for result in results:
        result.setdefault("importance_compute_mode", args.importance_mode_used)
    results.sort(key=lambda row: safe_int(row.get("_candidate_order", -1), -1))
    apply_fdr_and_classification(results, args)

    write_template(template_path, template_info, args)
    write_results(result_path, results, args.block_sizes_parsed)
    write_summary(summary_path, results, template_info, args)
    write_prefilter_summary(prefilter_path, candidate_load_stats, coverage_prefilter_stats, args)
    write_run_manifest(
        run_manifest_path,
        args,
        torf_paths,
        (template_path, result_path, summary_path, prefilter_path),
        template_info,
        len(results),
    )

    sys.stderr.write(f"[ok] wrote {template_path}\n")
    sys.stderr.write(f"[ok] wrote {result_path}\n")
    sys.stderr.write(f"[ok] wrote {summary_path}\n")
    sys.stderr.write(f"[ok] wrote {prefilter_path}\n")
    sys.stderr.write(f"[ok] wrote {run_manifest_path}\n")


if __name__ == "__main__":
    main()
